"""The catalog reference pages: a :class:`CatalogSnapshot` rendered as MyST Markdown.

Pure text in, text out: :func:`render_pages` maps each page's path (relative to
the generated ``reference/catalog/`` directory) to its Markdown. The pages show
metadata only, never a rule's or prompt's full text: prompts are Jinja templates
whose text depends on detector facts, so each page links to its source instead.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Final

if TYPE_CHECKING:
    from collections.abc import Iterable, Sequence

    from catalog_snapshot import (
        CatalogSnapshot,
        HookEntry,
        PluginEntry,
        PromptEntry,
        RuleEntry,
        SectionEntry,
        SkillEntry,
    )

#: The first line of every generated page, so nobody edits the output by hand.
GENERATED_NOTE: Final = "% Generated by docs/_ext/catalog_pages.py at build time. Edit catalog/."

#: Hook family titles, in the order docs/hooks.md presents them. A family missing
#: here sorts after these, titled from its directory name.
HOOK_FAMILY_TITLES: Final = {
    "protect": "Protect the playbook",
    "verify": "Verify before done",
    "feedback": "Edit feedback",
    "safety": "Secrets and risky actions",
    "audit": "Audit",
}


def render_pages(snapshot: CatalogSnapshot, *, source_tree_url: str) -> dict[str, str]:
    """Every catalog page, keyed by its path under ``reference/catalog/``.

    ``source_tree_url`` prefixes a repo path to link its source, such as
    ``https://github.com/o/r/tree/main/``.

    Example: ``render_pages(snapshot, source_tree_url=url)["index.md"]`` starts with
    :data:`GENERATED_NOTE`.
    """
    pages = {
        "index.md": _index_page(snapshot),
        "prompts.md": _prompts_page(snapshot.prompts),
        "hooks.md": _hooks_page(snapshot.hooks),
    }
    for skill in snapshot.core_skills:
        pages[f"skills/{skill.id}.md"] = _skill_page(skill, source_tree_url)
    for plugin in snapshot.plugins:
        pages[f"plugins/{plugin_slug(plugin)}.md"] = _plugin_page(plugin, source_tree_url)
    return pages


def plugin_slug(plugin: PluginEntry) -> str:
    """The plugin's directory name, as ``overlays_enabled`` spells its last segment."""
    return plugin.layer.rsplit(".", 1)[-1]


def _index_page(snapshot: CatalogSnapshot) -> str:
    skills = [(f"[{s.id}](skills/{s.id}.md)", s.description) for s in snapshot.core_skills]
    plugins = [
        (f"[{plugin_slug(p)}](plugins/{plugin_slug(p)}.md)", p.description)
        for p in snapshot.plugins
    ]
    children = [
        *(f"skills/{s.id}" for s in snapshot.core_skills),
        *(f"plugins/{plugin_slug(p)}" for p in snapshot.plugins),
        "prompts",
        "hooks",
    ]
    return _page(
        "# Catalog",
        "The catalog is the content the engine renders into each harness's files: skills, "
        "rules, prompts and hooks. These pages are generated from `catalog/` at every "
        "build, so they always match the source.",
        "## Core skills",
        "Core skills are part of every consumer repo. The engine writes a skill only where "
        "its gate passes, so a skill about pytest appears only in a repo that uses pytest.",
        _table(("Skill", "What it guides"), skills),
        "## Always rules",
        "Always rules sit in always-loaded context. The agent reads them on every turn, "
        "whatever the task.",
        _rules_table(snapshot.always_rules),
        "## Bundled plugins",
        "A bundled plugin is an opt-in layer that ships inside the engine. Each plugin "
        "below is a framework, and a consumer repo turns on at most one framework.",
        _table(("Plugin", "What it adds"), plugins),
        "## Prompts and hooks",
        "[Prompts](prompts.md) lists the slash commands and the prompt sets that ship "
        "them. [Hooks](hooks.md) lists the assistant lifecycle hooks, by hook family.",
        _toctree(children),
    )


def _skill_page(skill: SkillEntry, source_tree_url: str) -> str:
    return _page(
        f"# {skill.id}",
        skill.description,
        _skill_facts(skill, source_tree_url),
        *_skill_body(skill),
    )


def _skill_facts(skill: SkillEntry, source_tree_url: str) -> str:
    facts = [
        ("Use when", skill.use_when),
        ("Covers", skill.files),
        ("Capabilities", ", ".join(skill.capabilities)),
        ("Source", _source_link(skill.source_path, source_tree_url)),
    ]
    return _field_list(facts)


def _skill_body(skill: SkillEntry) -> list[str]:
    blocks = [block for section in skill.sections for block in _section_blocks(section)]
    if skill.references:
        rows = [(f"`{ref.path}`", ref.open_when) for ref in skill.references]
        blocks += ["## References and examples", _table(("Path", "Open when"), rows)]
    return blocks


def _section_blocks(section: SectionEntry) -> list[str]:
    facts = _field_list([("Impact", section.impact), ("Open when", section.open_when)])
    return [f"## {section.title}", section.summary, facts, _rules_table(section.rules)]


def _plugin_page(plugin: PluginEntry, source_tree_url: str) -> str:
    facts = _field_list(
        [
            ("Framework name", f"`{plugin.name}`"),
            (
                "Turn it on",
                f'`framework = "{plugin.name}"` in `.coding-agent-playbook.toml`, '
                f"which `playbook init --framework {plugin.name}` writes",
            ),
            ("Source", _source_link(plugin.source_path, source_tree_url)),
        ]
    )
    blocks = [f"# {plugin_slug(plugin)}", plugin.description, plugin.credit, facts]
    blocks += _capability_blocks(plugin.skills)
    if plugin.always_rules:
        blocks += ["## Always rules", _rules_table(plugin.always_rules)]
    blocks.append("## Skills")
    for skill in plugin.skills:
        blocks += [f"### {skill.id}", skill.description, _skill_facts(skill, source_tree_url)]
    return _page(*blocks)


def _capability_blocks(skills: Sequence[SkillEntry]) -> list[str]:
    rows = [(f"`{cap}`", f"[{s.id}](#{s.id})") for s in skills for cap in s.capabilities]
    if not rows:
        return []
    lead = "A capability is a standard role, such as planning or review. Each row names the skill of this framework that fills it."
    return ["## Capabilities", lead, _table(("Capability", "Skill"), sorted(rows))]


def _prompts_page(prompts: Sequence[PromptEntry]) -> str:
    rows = [(p.name, f"`/{p.slash}`", p.description, ", ".join(p.prompt_sets)) for p in prompts]
    return _page(
        "# Prompts",
        "A prompt is a named task you invoke as a slash command. A consumer repo "
        "chooses one prompt set, and every set renders the same prompt names.",
        _table(("Prompt", "Slash command", "What it does", "Prompt sets"), rows),
    )


def _hooks_page(hooks: Sequence[HookEntry]) -> str:
    blocks = [
        "# Hooks",
        "The catalog's assistant lifecycle hooks, grouped by hook family. "
        "[Hooks](../../hooks.md) explains how to turn them on, what the tiers mean and "
        "where each harness runs them.",
    ]
    for family in _families(hooks):
        rows = [_hook_row(hook) for hook in hooks if hook.family == family]
        blocks += [f"## {_family_title(family)}", _table(_HOOK_COLUMNS, rows)]
    return _page(*blocks)


_HOOK_COLUMNS: Final = ("Hook", "What it does", "Events", "Tier", "Harnesses")


def _hook_row(hook: HookEntry) -> tuple[str, ...]:
    events = ", ".join(f"`{event}`" for event in hook.events)
    return (f"{hook.name} (`{hook.id}`)", hook.summary, events, hook.tier, ", ".join(hook.supports))


def _families(hooks: Iterable[HookEntry]) -> list[str]:
    known = list(HOOK_FAMILY_TITLES)
    present = {hook.family for hook in hooks}
    return [f for f in known if f in present] + sorted(present - set(known))


def _family_title(family: str) -> str:
    return HOOK_FAMILY_TITLES.get(family, family.replace("_", " ").capitalize())


def _rules_table(rules: Sequence[RuleEntry]) -> str:
    rows = [(_rule_label(rule), rule.description) for rule in rules]
    return _table(("Rule", "What it says"), rows)


def _rule_label(rule: RuleEntry) -> str:
    origin = f" (from `{rule.origin}`)" if rule.origin else ""
    return f"{rule.name} (`{rule.id}`){origin}"


def _field_list(fields: Iterable[tuple[str, str]]) -> str:
    """A MyST field list (``:Name: value``), shown like the parameter lists of API docs.

    Fields with an empty value are left out.
    """
    return "\n".join(f":{name}: {_cell(value)}" for name, value in fields if value)


def _source_link(path: str, source_tree_url: str) -> str:
    return f"[`{path}`]({source_tree_url}{path})" if path else ""


def _table(header: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    """A GFM table; cells are flattened to one line and their pipes escaped."""
    lines = [_row(header), _row(["---"] * len(header))]
    lines += [_row(row) for row in rows]
    return "\n".join(lines)


def _row(cells: Iterable[str]) -> str:
    return "| " + " | ".join(_cell(cell) for cell in cells) + " |"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _toctree(children: Iterable[str]) -> str:
    entries = "\n".join(children)
    return f"```{{toctree}}\n:hidden:\n\n{entries}\n```"


def _page(*blocks: str) -> str:
    """Join non-empty blocks with blank lines, under the generated-file note."""
    return "\n\n".join([GENERATED_NOTE, *(block for block in blocks if block)]) + "\n"
