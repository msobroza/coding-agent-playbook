def _read(skill_id: str, relative: str = "SKILL.md") -> str:
    return (SKILLS_ROOT / skill_id / relative).read_text(encoding="utf-8")


def _lines(skill_id: str, relative: str = "SKILL.md") -> list[str]:
    return _read(skill_id, relative).split("\n")


def _relative_files(skill_id: str) -> list[str]:
    return sorted(p.relative_to(SKILLS_ROOT / skill_id).as_posix() for p in skill_files(skill_id))


def _markdown_files(skill_id: str) -> list[str]:
    return [relative for relative in _relative_files(skill_id) if relative.endswith(".md")]


def _attributions_section(skill_id: str) -> str:
    """One per-skill section of ``ATTRIBUTIONS.md``, whitespace-normalised (the bullets wrap)."""
    text = (PLUGIN_ROOT / "ATTRIBUTIONS.md").read_text(encoding="utf-8")
    section = text.split(f"\n### {skill_id}\n", 1)[1].split("\n### ", 1)[0]
    return " ".join(section.split())


