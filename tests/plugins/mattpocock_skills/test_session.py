@pytest.mark.parametrize("skill_id", _T08_IDS)
def test_files_keep_upstream_byte_hygiene(skill_id: str) -> None:
    for path in skill_files(skill_id):
        data = path.read_bytes()
        assert b"\r" not in data, f"{path.name}: CR"
        assert data.endswith(b"\n") and not data.endswith(b"\n\n"), f"{path.name}: final newline"
        trailing = [n for n, line in enumerate(data.split(b"\n"), 1) if line != line.rstrip()]
        assert trailing == [], f"{path.name}: trailing whitespace on lines {trailing}"


@pytest.mark.parametrize("skill_id", _T08_IDS)
def test_non_ascii_appears_only_where_upstream_has_it(skill_id: str) -> None:
    for relative in _markdown_files(skill_id):
        found = {
            number: ord(char)
            for number, line in enumerate(_lines(skill_id, relative), 1)
            for char in line
            if ord(char) > 127
        }
        assert found == _NON_ASCII.get((skill_id, relative), {}), f"{skill_id}/{relative}"


@pytest.mark.parametrize("skill_id", _T08_IDS)
def test_load_targets_are_the_table_row(skill_id: str) -> None:
    found = {
        (relative, match.group(1))
        for relative in _markdown_files(skill_id)
        for match in LOAD_RE.finditer(_read(skill_id, relative))
    }
    assert found == {("SKILL.md", target) for target in _LOAD_TARGETS[skill_id]}


@pytest.mark.parametrize("skill_id", _T08_IDS)
def test_no_source_file_carries_the_sentinel(skill_id: str) -> None:
    # The engine writes the sentinel at sync; a source that carried it would look generated.
    for path in skill_files(skill_id):
        assert SENTINEL not in path.read_text(encoding="utf-8"), path.name
        assert not file_has_sentinel(path), path.name


@pytest.mark.parametrize("skill_id", _T08_IDS)
def test_relative_markdown_links_are_exactly_the_rewritten_ones(skill_id: str) -> None:
    for relative in _markdown_files(skill_id):
        path = SKILLS_ROOT / skill_id / relative
        targets = [link.target for link in extract_markdown_links(path.read_text("utf-8"))]
        assert targets == _LINK_TARGETS.get((skill_id, relative), []), f"{skill_id}/{relative}"
        local = [target for target in targets if not target.startswith("#")]
        assert all((path.parent / target).is_file() for target in local), f"{skill_id}/{relative}"


