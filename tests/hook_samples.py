def hook_mapping(**overrides: Any) -> dict[str, Any]:
    """A minimal valid frontmatter mapping for hook ``guard-x``; ``overrides`` replace keys."""
    data: dict[str, Any] = {
        "id": "guard-x",
        "name": "Guard X",
        "description": "Deny x.",
        "tier": "default",
        "events": ["pre_tool_use"],
        "decisions": ["deny", "none"],
        "timeout": 2,
        "on_error": "ask",
        "supports": ["claude_code"],
        "handler": {"builtin": "guard_x"},
    }
    data.update(overrides)
    return data


def hook_frontmatter(**overrides: Any) -> HookFrontmatter:
    """:func:`hook_mapping` parsed through ``HookFrontmatter.from_mapping``."""
    return HookFrontmatter.from_mapping(hook_mapping(**overrides), where=HOOK_WHERE)


def sample_hook(
    source_package: str = "<repo-local>", *, path: str | None = None, **overrides: Any
) -> Hook:
    """An in-memory hook ``guard-x`` from ``source_package`` (``id=`` renames it).

    ``overrides`` replace frontmatter keys of :func:`hook_mapping`; ``path`` sets
    ``source_path``. Example: ``sample_hook("acme", tier="opt-in")``.
    """
    source_path = None if path is None else Path(path)
    return Hook(
        hook_frontmatter(**overrides), "Advice.\n", "Advice.\n", False, source_path, source_package
    )


def resolved_hook(
    hook_id: str = "guard-x",
    *,
    name: str = "Guard X",
    events: Sequence[str] = ("pre_tool_use",),
    matcher: Mapping[str, Mapping[str, list[str]]] | None = None,
    timeout: float = 2.0,
    on_error: str = "ask",
    supports: Sequence[str] = ("claude_code",),
    declared_supports: Sequence[str] | None = None,
    config: Mapping[str, Any] | None = None,
    body: str = "Advice.\n",
    source_package: str = "<repo-local>",
    summary: str = "",
) -> ResolvedHook:
    """A hand-built :class:`ResolvedHook`, with no gating, for the K3 renderers and planners.

    ``supports`` is the narrowed (effective) list, ``declared_supports`` the
    frontmatter's (default: the same); ``on_error`` is clamped per event as the
    effective view does; ``matcher`` gives authored entries per event (the rest
    match everything). The advisory carries ``body`` through ``with_rendered_body``;
    ``summary`` is the frontmatter's one-line guardrail (``""``: none).
    Example: ``resolved_hook("guard-y", events=("stop",), supports=("claude_code", "opencode"))``.
    """
    authored = {event: dict(entry) for event, entry in (matcher or {}).items()}
    handler_config: dict[str, Any] = copy.deepcopy(dict(config or {}))
    handler = {"builtin": "guard_x", "config": handler_config}
    definition = Hook(
        hook_frontmatter(
            id=hook_id,
            name=name,
            events=list(events),
            matcher=authored,
            timeout=timeout,
            on_error=on_error,
            supports=list(supports if declared_supports is None else declared_supports),
            handler=handler,
            summary=summary,
        ),
        body,
        body,
        False,
        None,
        source_package,
    )
    fm = definition.frontmatter
    return ResolvedHook(
        id=hook_id,
        source_package=source_package,
        events=tuple(events),
        priority=fm.priority,
        matcher={event: copy.deepcopy(fm.matcher.get(event, HookMatcher())) for event in events},
        handlers={
            event: ResolvedHandler("builtin", name="guard_x", config=copy.deepcopy(handler_config))
            for event in events
        },
        decisions=tuple(fm.decisions),
        timeout=float(timeout),
        on_error={event: effective_on_error(on_error, EventName(event)) for event in events},
        supports=tuple(supports),
        mandatory=False,
        script_sha256=None,
        advisory=definition.to_advisory_rule(),
        definition=definition,
    ).with_rendered_body(body)


def write_hook_md(
    root: Path,
    text: str,
    *,
    hook_id: str = "guard-x",
    name: str = "HOOK.md",
    scripts: bool = False,
) -> Path:
    """Write ``<root>/protect/<hook_id>/<name>`` (plus ``scripts/`` when asked); return its path."""
    hook_dir = root / "protect" / hook_id
    hook_dir.mkdir(parents=True)
    if scripts:
        (hook_dir / "scripts").mkdir()
    path = hook_dir / name
    path.write_text(text, encoding="utf-8")
    return path


def write_hook(
    root: Path,
    hook_id: str = "guard-x",
    *,
    category: str = "protect",
    marker: str = "HOOK.md",
    body: str = "Advice.\n",
    scripts: bool = False,
    **frontmatter: Any,
) -> Path:
    """Write ``<root>/<category>/<hook_id>/<marker>`` from :func:`hook_mapping`; return its path.

    ``frontmatter`` replaces keys of the minimal valid mapping (``id`` is
    ``hook_id``); an empty ``category`` puts the hook directly under ``root``.
    Example: ``write_hook(tmp_path / "playbook" / "hooks", "guard-y", tier="opt-in")``.
    """
    hook_dir = root / category / hook_id if category else root / hook_id
    hook_dir.mkdir(parents=True, exist_ok=True)
    if scripts:
        (hook_dir / "scripts").mkdir(exist_ok=True)
    path = hook_dir / marker
    data = hook_mapping(**{"id": hook_id, **frontmatter})
    path.write_text(format_frontmatter(data, body), encoding="utf-8")
    return path


def resolved_from_disk(
    root: Path,
    hook_id: str = "guard-x",
    *,
    body: str = "Advice.\n",
    templated: bool = False,
    advisory: bool = True,
    **frontmatter: Any,
) -> ResolvedHook:
    """An external-command hook written under ``root`` with ``scripts/``, resolved as sync would.

    ``scripts/check.sh`` is executable, ``scripts/lib/data.txt`` is not. The hook
    goes through the real ``resolve_effective_hooks`` with ``[hooks] enabled``,
    so ``definition`` is the on-disk ``Hook`` (an un-rendered ``.md.j2`` body
    stays as written). Example: ``resolved_from_disk(tmp_path / "src", templated=True)``.
    """
    marker = "HOOK.md.j2" if templated else "HOOK.md"
    handler = {"command": "sh", "script": "scripts/check.sh", "args": ["--fast"]}
    path = write_hook(
        root,
        hook_id,
        category="",
        marker=marker,
        body=body,
        scripts=True,
        **{"handler": handler, **frontmatter},
    )
    script = path.parent / "scripts" / "check.sh"
    script.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    script.chmod(script.stat().st_mode | stat.S_IXUSR)
    (path.parent / "scripts" / "lib").mkdir()
    (path.parent / "scripts" / "lib" / "data.txt").write_text("data\n", encoding="utf-8")
    hook = Hook.from_markdown(path, "<repo-local>")
    view = resolve_effective_hooks(
        [hook],
        [],
        HooksConfig(enabled=True, advisory=advisory),
        GuardrailsConfig(),
        cast("Facts", {}),
        root,
        adapters_enabled=["claude_code"],
    )
    [resolved] = view.resolved
    return resolved


#: The import name of the sample handler distribution (see :func:`install_sample_handlers`).
SAMPLE_HANDLERS_PACKAGE = "playbook_sample_handlers"
#: The builtin names the sample hooks bind (``hook_mapping`` uses ``guard_x``).
SAMPLE_HANDLER_NAMES = ("guard_x", "guard_y", "guard_z")

_SAMPLE_HANDLERS_SOURCE = '''\
"""Sample hook handlers, registered through the hook_handlers entry-point group."""

from coding_agent_playbook.hook_runtime.registry import ConfigKey, register_hook_handler

EVENTS = [
    "session_start", "user_prompt_submit", "pre_tool_use", "post_tool_use",
    "post_tool_use_failure", "stop", "subagent_stop", "pre_compact", "session_end",
]
DECISIONS = ["deny", "ask", "context", "none"]
SCHEMA = {
    "budget_s": ConfigKey("number"),
    "limits": ConfigKey("table"),
    "extra_protected": ConfigKey("list", "extend"),
    "mode": ConfigKey("string", "strictest", ("off", "warn", "block")),
}

{handlers}
'''
_SAMPLE_HANDLER = """
@register_hook_handler({name!r}, events=EVENTS, decisions=DECISIONS, config_schema=SCHEMA)
def {name}(ev, ctx):
    return None
"""


def install_sample_handlers(root: Path) -> None:
    """Write an installed-looking distribution under ``root`` whose entry points provide
    :data:`SAMPLE_HANDLER_NAMES` in the ``coding_agent_playbook.hook_handlers`` group.

    Put ``root`` on ``sys.path`` and ``importlib.metadata`` finds it, exactly as it
    finds an overlay's handler package (the catalog's real lookup path; §D.3.1).
    """
    package = root / SAMPLE_HANDLERS_PACKAGE
    package.mkdir(parents=True)
    handlers = "".join(_SAMPLE_HANDLER.format(name=name) for name in SAMPLE_HANDLER_NAMES)
    (package / "__init__.py").write_text(
        _SAMPLE_HANDLERS_SOURCE.replace("{handlers}", handlers), encoding="utf-8"
    )
    dist = root / f"{SAMPLE_HANDLERS_PACKAGE}-1.0.dist-info"
    dist.mkdir()
    (dist / "METADATA").write_text(
        "Metadata-Version: 2.1\nName: playbook-sample-handlers\nVersion: 1.0\n", encoding="utf-8"
    )
    points = "".join(
        f"{name} = {SAMPLE_HANDLERS_PACKAGE}:{name}\n" for name in SAMPLE_HANDLER_NAMES
    )
    (dist / "entry_points.txt").write_text(
        f"[coding_agent_playbook.hook_handlers]\n{points}", encoding="utf-8"
    )
