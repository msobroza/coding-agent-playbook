"""Shared HOOK.md sample data for the hook tests (specs/prK-lifecycle-hooks.md §A).

Plain builders, not fixtures, so parametrize lists can call them at import time.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from coding_agent_playbook.types import Hook, HookFrontmatter, format_frontmatter

#: The ``where`` label the builders parse under.
HOOK_WHERE = "playbook/hooks/guard-x/HOOK.md"

#: The §A.9 worked example (the body shortened).
GUARD_GENERATED_OUTPUTS_MD = """\
---
id: guard-generated-outputs
name: Guard generated outputs
description: Deny hand-edits to files that playbook sync generates and point at the canonical source.
version: 1
tier: default
priority: 10
events: [pre_tool_use]
matcher:
  pre_tool_use:
    tools: [edit, write, notebook_edit, shell]
handler:
  builtin: guard_generated_outputs
  config:
    extra_protected: []
decisions: [deny, ask, none]
timeout: 2
on_error: ask
supports: [claude_code, opencode]
tags: [protect, drift]
---
Files that begin with the AUTOGENERATED sentinel are produced by `playbook sync`.
Edit the canonical source under `playbook/` instead.
"""


def hook_mapping(**overrides: Any) -> dict[str, Any]:
    """A minimal valid frontmatter mapping for hook ``guard-x``; ``overrides`` replace keys."""
    data: dict[str, Any] = {
        "id": "guard-x",
        "name": "Guard X",
        "description": "Deny x.",
        "tier": "default",
        "events": ["pre_tool_use"],
        "decisions": ["deny", "none"],
        "timeout": 2,
        "on_error": "ask",
        "supports": ["claude_code"],
        "handler": {"builtin": "guard_x"},
    }
    data.update(overrides)
    return data


def hook_frontmatter(**overrides: Any) -> HookFrontmatter:
    """:func:`hook_mapping` parsed through ``HookFrontmatter.from_mapping``."""
    return HookFrontmatter.from_mapping(hook_mapping(**overrides), where=HOOK_WHERE)


def sample_hook(
    source_package: str = "<repo-local>", *, path: str | None = None, **overrides: Any
) -> Hook:
    """An in-memory hook ``guard-x`` from ``source_package`` (``id=`` renames it).

    ``overrides`` replace frontmatter keys of :func:`hook_mapping`; ``path`` sets
    ``source_path``. Example: ``sample_hook("acme", tier="opt-in")``.
    """
    source_path = None if path is None else Path(path)
    return Hook(
        hook_frontmatter(**overrides), "Advice.\n", "Advice.\n", False, source_path, source_package
    )


def write_hook_md(
    root: Path,
    text: str,
    *,
    hook_id: str = "guard-x",
    name: str = "HOOK.md",
    scripts: bool = False,
) -> Path:
    """Write ``<root>/protect/<hook_id>/<name>`` (plus ``scripts/`` when asked); return its path."""
    hook_dir = root / "protect" / hook_id
    hook_dir.mkdir(parents=True)
    if scripts:
        (hook_dir / "scripts").mkdir()
    path = hook_dir / name
    path.write_text(text, encoding="utf-8")
    return path


def write_hook(
    root: Path,
    hook_id: str = "guard-x",
    *,
    category: str = "protect",
    marker: str = "HOOK.md",
    body: str = "Advice.\n",
    scripts: bool = False,
    **frontmatter: Any,
) -> Path:
    """Write ``<root>/<category>/<hook_id>/<marker>`` from :func:`hook_mapping`; return its path.

    ``frontmatter`` replaces keys of the minimal valid mapping (``id`` is
    ``hook_id``); an empty ``category`` puts the hook directly under ``root``.
    Example: ``write_hook(tmp_path / "playbook" / "hooks", "guard-y", tier="opt-in")``.
    """
    hook_dir = root / category / hook_id if category else root / hook_id
    hook_dir.mkdir(parents=True, exist_ok=True)
    if scripts:
        (hook_dir / "scripts").mkdir(exist_ok=True)
    path = hook_dir / marker
    data = hook_mapping(**{"id": hook_id, **frontmatter})
    path.write_text(format_frontmatter(data, body), encoding="utf-8")
    return path
