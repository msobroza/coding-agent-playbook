@pytest.mark.parametrize("rel", _ENGINE_FILES, ids=str)
def test_stale_engine_file_is_deleted_when_not_rewritten(tmp_path: Path, rel: Path) -> None:
    """An empty buffer writes nothing, so a prior render must not linger."""
    stale = _write(tmp_path, rel, f"{sentinel_line('html')}\n# old\n")

    deleted = ClaudeCodeAdapter().cleanup_stale(set(), tmp_path)

    assert deleted == [stale]
    assert not stale.exists()


@pytest.mark.parametrize("rel", _ENGINE_FILES, ids=str)
def test_engine_file_in_written_paths_is_kept(tmp_path: Path, rel: Path) -> None:
    fresh = _write(tmp_path, rel, f"{sentinel_line('html')}\n# fresh\n")

    assert ClaudeCodeAdapter().stale_outputs({fresh.resolve()}, tmp_path) == []


@pytest.mark.parametrize("rel", _ENGINE_FILES, ids=str)
def test_user_authored_file_without_sentinel_is_kept(tmp_path: Path, rel: Path) -> None:
    user_file = _write(tmp_path, rel, "# My own file\n")

    assert ClaudeCodeAdapter().cleanup_stale(set(), tmp_path) == []
    assert user_file.is_file()


@pytest.mark.parametrize("rel", _ENGINE_FILES, ids=str)
def test_binary_engine_path_is_skipped(tmp_path: Path, rel: Path) -> None:
    target = tmp_path / rel
    target.parent.mkdir(parents=True)
    target.write_bytes(b"\x80\x81\x82\x83")

    assert ClaudeCodeAdapter().stale_outputs(set(), tmp_path) == []


def test_both_stale_engine_files_are_reported(tmp_path: Path) -> None:
    stale = [_write(tmp_path, rel, f"{sentinel_line('html')}\n# old\n") for rel in _ENGINE_FILES]

    assert ClaudeCodeAdapter().stale_outputs(set(), tmp_path) == stale
    assert all(path.is_file() for path in stale)  # stale_outputs deletes nothing


def test_other_rules_files_are_never_reported(tmp_path: Path) -> None:
    """Even a sentinel-tagged sibling in ``.claude/rules/`` is not engine-owned."""
    sentinel_text = f"{sentinel_line('html')}\n# other\n"
    siblings = [
        _write(tmp_path, Path(".claude/rules/team.md"), "# Team rule\n"),
        _write(tmp_path, Path(".claude/rules/old-engine-name.md"), sentinel_text),
        _write(tmp_path, Path(".claude/rules/nested/deep.md"), sentinel_text),
    ]
    stale = _write(tmp_path, _RULES_FILE, sentinel_text)

    deleted = ClaudeCodeAdapter().cleanup_stale(set(), tmp_path)

    assert deleted == [stale]
    assert all(path.is_file() for path in siblings)
