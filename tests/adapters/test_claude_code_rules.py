"""Claude Code rule output: a rule-free ``.claude/CLAUDE.md`` stub plus one rules file (SPEC §10.3.1).

Why two files: OpenCode v1 attaches the first ``AGENTS.md`` / ``CLAUDE.md`` of
every directory between a file it reads and its working directory, so a
rule-bearing ``.claude/CLAUDE.md`` handed it a second full copy of the rules
(and the Claude-only heartbeat line) on any read under ``.claude/``. No
OpenCode version reads ``.claude/rules/``, while Claude Code loads an unscoped
``.claude/rules/*.md`` at launch like ``.claude/CLAUDE.md``. The stub must still
exist: any CLAUDE.md stops Claude Code from also reading the root ``AGENTS.md``
natively, and a rules file does not count for that, so without the stub Claude
would load the rules twice.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from coding_agent_playbook._sentinel import sentinel_line
from coding_agent_playbook.adapters.agents_md_adapter import AgentsMdAdapter
from coding_agent_playbook.adapters.claude_code_adapter import ClaudeCodeAdapter
from coding_agent_playbook.adapters.claude_rule_paths import (
    CLAUDE_CODE_COMPOSITES,
    CLAUDE_MD_PATH,
    CLAUDE_RULES_PATH,
)
from coding_agent_playbook.types import Rule, RuleFrontmatter
from tests.import_probe import new_modules_after

_CLAUDE_MD = Path(".claude") / "CLAUDE.md"
_RULES_FILE = Path(".claude") / "rules" / "coding-agent-playbook.md"
_ENGINE_FILES = [_CLAUDE_MD, _RULES_FILE]
_GENERATED_LINE = "This file is generated by coding-agent-playbook."
_STUB = f"{sentinel_line('html')}\n# CLAUDE.md\n\n{_GENERATED_LINE}\n"


def _make_rule(
    *,
    rule_id: str = "python-typing",
    name: str = "Python typing standards",
    priority: int = 50,
    globs: list[str] | None = None,
    body: str = "# Python typing\n\nUse type hints.\n",
) -> Rule:
    return Rule(
        frontmatter=RuleFrontmatter(
            id=rule_id,
            name=name,
            description="A test rule",
            scope="scoped" if globs else "always",
            globs=globs or [],
            priority=priority,
        ),
        body=body,
        template_body=body,
        is_templated=False,
        source_path=None,
        source_package="test",
    )


def _finalize(repo_root: Path, *rules: Rule) -> list[Path]:
    adapter = ClaudeCodeAdapter()
    for rule in rules:
        adapter.write_rule(rule, repo_root)
    return adapter.finalize(repo_root)


def _write(repo_root: Path, rel: Path, text: str) -> Path:
    target = repo_root / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return target


def test_path_constants_name_the_two_engine_files() -> None:
    assert (_CLAUDE_MD.as_posix(), _RULES_FILE.as_posix()) == (CLAUDE_MD_PATH, CLAUDE_RULES_PATH)
    assert CLAUDE_CODE_COMPOSITES == (CLAUDE_MD_PATH, CLAUDE_RULES_PATH)


def test_paths_module_is_a_stdlib_leaf() -> None:
    """The guard tables import the paths without the adapter's renderer (jinja2, yaml)."""
    loaded = new_modules_after("import coding_agent_playbook._guard_config_protect")

    assert "coding_agent_playbook.adapters.claude_rule_paths" in loaded
    assert not {"jinja2", "yaml", "coding_agent_playbook.renderer"} & set(loaded)
    assert "coding_agent_playbook.adapters.claude_code_adapter" not in loaded


# --------------------------------------------------------------------------- #
# finalize: the stub and the rules file
# --------------------------------------------------------------------------- #


def test_finalize_writes_the_stub_and_the_rules_file(tmp_path: Path) -> None:
    written = _finalize(tmp_path, _make_rule())

    assert written == [tmp_path / _CLAUDE_MD, tmp_path / _RULES_FILE]
    assert all(path.is_file() for path in written)


def test_claude_md_is_the_rule_free_header_stub(tmp_path: Path) -> None:
    """Regression: OpenCode v1 attaches ``.claude/CLAUDE.md`` on reads under
    ``.claude/``, so it must carry no rule text — and no pointer to the rules
    file, which would invite the model to read the rules again."""
    _finalize(tmp_path, _make_rule(name="Typing rule", body="Use type hints everywhere.\n"))

    content = (tmp_path / _CLAUDE_MD).read_text(encoding="utf-8")

    assert content == _STUB
    assert "Typing rule" not in content
    assert "Use type hints everywhere." not in content
    assert "rules/" not in content


def test_rules_file_header_has_no_frontmatter(tmp_path: Path) -> None:
    """No ``paths:`` frontmatter: Claude Code loads an unscoped rules file at launch."""
    _finalize(tmp_path, _make_rule(globs=["**/*.py"]))

    content = (tmp_path / _RULES_FILE).read_text(encoding="utf-8")

    assert content.splitlines()[:5] == [
        sentinel_line("html"),
        "# Project rules (coding-agent-playbook)",
        "",
        _GENERATED_LINE,
        "",
    ]
    assert not content.startswith("---")
    assert "paths:" not in content


def test_rules_file_orders_sections_by_priority_then_id(tmp_path: Path) -> None:
    _finalize(
        tmp_path,
        _make_rule(rule_id="z", priority=50, name="Z rule"),
        _make_rule(rule_id="b", priority=20, name="B rule"),
        _make_rule(rule_id="a", priority=50, name="A rule"),
    )

    content = (tmp_path / _RULES_FILE).read_text(encoding="utf-8")

    assert content.index("## B rule") < content.index("## A rule") < content.index("## Z rule")


def test_rules_file_sections_are_byte_identical_to_agents_md(tmp_path: Path) -> None:
    rules = [
        _make_rule(rule_id="a", priority=10, name="A rule", globs=["**/*.py"]),
        _make_rule(rule_id="b", priority=20, name="B rule", body="Plain body.\n"),
    ]
    _finalize(tmp_path, *rules)
    agents = AgentsMdAdapter()
    for rule in rules:
        agents.write_rule(rule, tmp_path)
    [agents_md] = agents.finalize(tmp_path)

    marker = f"{_GENERATED_LINE}\n\n"
    rules_sections = (tmp_path / _RULES_FILE).read_text(encoding="utf-8").split(marker, 1)[1]
    agents_sections = agents_md.read_text(encoding="utf-8").split(marker, 1)[1]

    assert rules_sections == agents_sections
    assert "## A rule" in rules_sections


def test_finalize_with_no_rules_writes_neither_file(tmp_path: Path) -> None:
    assert _finalize(tmp_path) == []
    assert not (tmp_path / ".claude").exists()


def test_output_locations_declare_the_rules_file_not_its_directory() -> None:
    """Users own every other ``.claude/rules/*.md``: only the one file is engine-owned."""
    locations = ClaudeCodeAdapter.output_locations

    assert ".claude/rules/coding-agent-playbook.md" in locations
    assert ".claude/CLAUDE.md" in locations
    assert ".claude/rules/" not in locations


