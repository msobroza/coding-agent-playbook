def test_finalize_writes_the_stub_and_the_rules_file(tmp_path: Path) -> None:
    written = _finalize(tmp_path, _make_rule())

    assert written == [tmp_path / _CLAUDE_MD, tmp_path / _RULES_FILE]
    assert all(path.is_file() for path in written)


def test_claude_md_is_the_rule_free_header_stub(tmp_path: Path) -> None:
    """Regression: OpenCode v1 attaches ``.claude/CLAUDE.md`` on reads under
    ``.claude/``, so it must carry no rule text — and no pointer to the rules
    file, which would invite the model to read the rules again."""
    _finalize(tmp_path, _make_rule(name="Typing rule", body="Use type hints everywhere.\n"))

    content = (tmp_path / _CLAUDE_MD).read_text(encoding="utf-8")

    assert content == _STUB
    assert "Typing rule" not in content
    assert "Use type hints everywhere." not in content
    assert "rules/" not in content


def _windows_write_text(
    self: Path,
    data: str,
    encoding: str | None = None,
    errors: str | None = None,
    newline: str | None = None,
) -> int:
    """``Path.write_text`` as it behaves on Windows: text mode turns each LF into CRLF."""
    text = data if newline in ("", "\n") else data.replace("\n", "\r\n")
    return self.write_bytes(text.encode(encoding or "utf-8", errors or "strict"))


def test_both_files_are_lf_even_where_text_mode_writes_crlf(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Regression (final review): the stub went through ``write_text`` (CRLF on
    Windows) while the rules file is written as bytes (LF), so the two files of
    one adapter differed in line endings, and the stub's hash from POSIX's."""
    monkeypatch.setattr(Path, "write_text", _windows_write_text)

    _finalize(tmp_path, _make_rule())

    assert (tmp_path / _CLAUDE_MD).read_bytes() == _STUB.encode("utf-8")
    assert b"\r" not in (tmp_path / _RULES_FILE).read_bytes()


def test_rules_file_header_has_no_frontmatter(tmp_path: Path) -> None:
    """No ``paths:`` frontmatter: Claude Code loads an unscoped rules file at launch."""
    _finalize(tmp_path, _make_rule(globs=["**/*.py"]))

    content = (tmp_path / _RULES_FILE).read_text(encoding="utf-8")

    assert content.splitlines()[:5] == [
        sentinel_line("html"),
        "# Project rules (coding-agent-playbook)",
        "",
        _GENERATED_LINE,
        "",
    ]
    assert not content.startswith("---")
    assert "paths:" not in content


def test_rules_file_orders_sections_by_priority_then_id(tmp_path: Path) -> None:
    _finalize(
        tmp_path,
        _make_rule(rule_id="z", priority=50, name="Z rule"),
        _make_rule(rule_id="b", priority=20, name="B rule"),
        _make_rule(rule_id="a", priority=50, name="A rule"),
    )

    content = (tmp_path / _RULES_FILE).read_text(encoding="utf-8")

    assert content.index("## B rule") < content.index("## A rule") < content.index("## Z rule")


def test_rules_file_sections_are_byte_identical_to_agents_md(tmp_path: Path) -> None:
    rules = [
        _make_rule(rule_id="a", priority=10, name="A rule", globs=["**/*.py"]),
        _make_rule(rule_id="b", priority=20, name="B rule", body="Plain body.\n"),
    ]
    _finalize(tmp_path, *rules)
    agents = AgentsMdAdapter()
    for rule in rules:
        agents.write_rule(rule, tmp_path)
    [agents_md] = agents.finalize(tmp_path)

    marker = f"{_GENERATED_LINE}\n\n"
    rules_sections = (tmp_path / _RULES_FILE).read_text(encoding="utf-8").split(marker, 1)[1]
    agents_sections = agents_md.read_text(encoding="utf-8").split(marker, 1)[1]

    assert rules_sections == agents_sections
    assert "## A rule" in rules_sections


def test_finalize_with_no_rules_writes_neither_file(tmp_path: Path) -> None:
    assert _finalize(tmp_path) == []
    assert not (tmp_path / ".claude").exists()


