def test_rules_file_skips_member_rules_and_gives_an_unrunnable_hook_one_line(
    tmp_path: Path,
) -> None:
    """D26: a hook Claude Code cannot run is one guardrail line, no longer a full section."""
    elsewhere = resolved_hook("guard-b", name="Guard B", supports=("opencode",))

    content = _claude_rules_file(tmp_path, [_member_rule()], [], [elsewhere])

    assert "Use type hints." not in content
    assert content == _RULES_HEAD + _GUARDRAILS + "- `guard-b`: Advice.\n"


def test_rules_file_guardrails_sit_between_the_where_section_and_the_heartbeat(
    tmp_path: Path,
) -> None:
    """The order AGENTS.md uses, with the heartbeat line still closing the file."""
    briefing = resolved_hook(_BRIEFING, events=("session_start",))
    elsewhere = resolved_hook("guard-b", supports=("opencode",), summary="Ask first.")

    content = _claude_rules_file(
        tmp_path, [_always_rule()], [_member_skill()], [briefing, elsewhere]
    )

    assert content == (
        _RULES_HEAD
        + _ALWAYS_SECTION
        + "\n"
        + _WHERE
        + "\n"
        + _GUARDRAILS
        + "- `guard-b`: Ask first.\n"
        + "\n"
        + CLAUDE_HEARTBEAT_LINE
        + "\n"
    )


def test_rules_file_where_section_precedes_heartbeat(tmp_path: Path) -> None:
    briefing = resolved_hook(_BRIEFING, events=("session_start",))

    content = _claude_rules_file(
        tmp_path, [_always_rule(), _member_rule()], [_member_skill()], [briefing]
    )

    assert content == (
        _RULES_HEAD + _ALWAYS_SECTION + "\n" + _WHERE + "\n" + CLAUDE_HEARTBEAT_LINE + "\n"
    )


def test_rules_file_written_with_only_a_where_entry(tmp_path: Path) -> None:
    content = _claude_rules_file(tmp_path, [_member_rule()], [_member_skill()], [])

    assert content == _RULES_HEAD + _WHERE


def test_rules_file_without_member_skills_is_byte_identical(tmp_path: Path) -> None:
    today = _claude_rules_file(tmp_path / "today", [_always_rule()], [], [])

    after = _claude_rules_file(tmp_path / "after", [_always_rule()], [_plain_skill()], [])

    assert after == today == _RULES_HEAD + _ALWAYS_SECTION


def test_where_section_is_byte_identical_in_agents_md_and_rules_file(tmp_path: Path) -> None:
    second = sample_member_skill("ml-data", sample_member_reference("ml-serialization"))
    second.frontmatter["playbook"]["files"] = "Code that loads models"
    skills = [second, _member_skill()]

    agents_md = _agents_md(tmp_path, [_always_rule()], skills, hooks=True)
    rules_file = _claude_rules_file(tmp_path, [_always_rule()], skills, [])

    where = _section_from(agents_md, "## Where guidance lives")
    assert where == _section_from(rules_file, "## Where guidance lives")
    assert where.index("skill `ml-data`") < where.index("skill `python-coding`")


def test_claude_md_stub_unchanged(tmp_path: Path) -> None:
    """Regression: the Where section goes to the rules file, never to the four-line stub."""
    _claude_rules_file(tmp_path, [_always_rule()], [_member_skill()], [])

    assert (tmp_path / CLAUDE_MD_PATH).read_text(encoding="utf-8") == _STUB


def _section_from(text: str, heading: str) -> str:
    """``text`` from ``heading`` through the first ``---`` separator line after it."""
    start = text.index(heading)
    end = text.index("\n---\n", start) + len("\n---\n")
    return text[start:end]
