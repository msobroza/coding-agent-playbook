"""``AGENTS.md`` and the Claude Code rules file carry always rules only (specs/prS-skills-context.md 6.4.6).

A member rule (one that names a skill in ``skill:``) reaches its readers as a
reference of that skill, so both composite adapters drop it; each written skill
with members and a ``playbook.files`` phrase adds one line to the generated
``## Where guidance lives`` section, which sits after the always sections and is
byte-identical in both files (E10). Hook advisories are built with
``skill=None`` and keep reaching the rules file in full (H16). Without member
skills both files keep today's bytes. The cases of section 6.8.5 live here
rather than in ``test_agents_md.py`` and ``test_claude_code_rules.py``, which
are already near the 500-line budget.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from coding_agent_playbook._sentinel import sentinel_line
from coding_agent_playbook.adapters.agents_md import AgentsMdAdapter
from coding_agent_playbook.adapters.claude_code.adapter import ClaudeCodeAdapter
from coding_agent_playbook.adapters.claude_code.hooks import CLAUDE_HEARTBEAT_LINE
from coding_agent_playbook.adapters.claude_code.paths import CLAUDE_MD_PATH, CLAUDE_RULES_PATH
from coding_agent_playbook.artifacts.rule import Rule, RuleFrontmatter
from coding_agent_playbook.artifacts.skill import Skill
from coding_agent_playbook.config.tables.hooks import HooksConfig
from coding_agent_playbook.skills.document import WhereEntry, where_guidance_section
from tests.hook_samples import GUARDRAILS_SECTION_HEAD, resolved_hook
from tests.member_skill_samples import sample_member_reference, sample_member_skill

if TYPE_CHECKING:
    from pathlib import Path

    from coding_agent_playbook.hook_policy import ResolvedHook

_GENERATED = "This file is generated by coding-agent-playbook.\n"
_AGENTS_HEAD = f"{sentinel_line('html')}\n# AGENTS.md\n\n{_GENERATED}\n"
_RULES_HEAD = f"{sentinel_line('html')}\n# Project rules (coding-agent-playbook)\n\n{_GENERATED}\n"
_STUB = f"{sentinel_line('html')}\n# CLAUDE.md\n\n{_GENERATED}"
_ALWAYS_SECTION = "## Project context\n\nAsk before coding.\n\n---\n"
_WHERE = where_guidance_section([WhereEntry("python-coding", "Any Python file")])
_GUARDRAILS = GUARDRAILS_SECTION_HEAD
_BRIEFING = "session-start-playbook-briefing"


def _always_rule() -> Rule:
    frontmatter = RuleFrontmatter(
        id="project-context", name="Project context", description="d", scope="always", priority=0
    )
    body = "Ask before coding.\n"
    return Rule(frontmatter, body, body, False, None, "coding_agent_playbook")


def _member_rule(rule_id: str = "python-typing") -> Rule:
    frontmatter = RuleFrontmatter(
        id=rule_id,
        name="Typing",
        description="d",
        scope="scoped",
        globs=["**/*.py"],
        priority=50,
        skill="python-coding",
    )
    body = "# Python typing\n\nUse type hints.\n"
    return Rule(frontmatter, body, body, False, None, "coding_agent_playbook")


def _member_skill() -> Skill:
    return sample_member_skill("python-coding", sample_member_reference())


def _plain_skill() -> Skill:
    frontmatter = {"id": "brainstorming", "name": "brainstorming", "description": "Explore ideas."}
    return Skill(frontmatter, "# Brainstorming\n", None, None, "superpowers")


def _agents_md(repo: Path, rules: list[Rule], skills: list[Skill], hooks: bool = False) -> str:
    """One AGENTS.md adapter pass as sync drives it: rules, skills, hooks, finalize."""
    adapter = AgentsMdAdapter()
    for rule in rules:
        assert adapter.write_rule(rule, repo) == []
    for skill in skills:
        assert adapter.write_skill(skill, repo) == []
    if hooks:
        adapter.write_hook(resolved_hook(body="Advice.\n"), repo)
    adapter.finalize(repo)
    return (repo / "AGENTS.md").read_text(encoding="utf-8")


def _claude_rules_file(
    repo: Path, rules: list[Rule], skills: list[Skill], hooks: list[ResolvedHook]
) -> str:
    """One Claude Code adapter pass (hooks on): rules, skills, hooks, finalize; the rules file."""
    adapter = ClaudeCodeAdapter()
    adapter.begin_sync(repo, None, hooks_config=HooksConfig(enabled=True))
    for rule in rules:
        assert adapter.write_rule(rule, repo) == []
    for skill in skills:
        adapter.write_skill(skill, repo)
    for hook in hooks:
        adapter.write_hook(hook, repo)
    adapter.finalize(repo)
    return (repo / CLAUDE_RULES_PATH).read_text(encoding="utf-8")


