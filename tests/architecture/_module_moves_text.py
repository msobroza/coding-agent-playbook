"""Text rules of the module-path rewrite script (specs/prT-package-layout.md 5.4.2).

R-DOC (prose: markdown lines, workflow comments, Python docstrings and comments),
R-TOML (``pyproject.toml``) and R-MIGRATION (the generated "Module paths" section of
MIGRATION.md), plus the ``<!-- module-moves: keep -->`` markers that fence history
off from R-DOC. Every function is pure: it reads one text and asks a ``Resolver`` for
current spellings, so the rules never touch the filesystem. Stdlib-only, like
``module_moves``.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import TYPE_CHECKING, Final, NamedTuple, Protocol

if TYPE_CHECKING:
    from collections.abc import Collection, Iterable, Sequence

KEEP_START: Final = "<!-- module-moves: keep -->"
KEEP_END: Final = "<!-- module-moves: end-keep -->"
SECTION_START: Final = "<!-- module-moves:start -->"
SECTION_END: Final = "<!-- module-moves:end -->"
_MARKERS: Final = {KEEP_START: "keep", SECTION_START: "section"}
_CLOSERS: Final = {KEEP_END: "keep", SECTION_END: "section"}

_ENGINE_DIR: Final = "src/coding_agent_playbook/"
#: A prefixed dotted engine name in prose, optionally ``module:attr``. The lookbehind
#: keeps ``coding_agent_playbook`` a whole leading segment.
_DOTTED: Final = re.compile(
    r"(?<![\w.])coding_agent_playbook(?:\.[A-Za-z_]\w*)+(?::[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*)?"
)
#: A relative path in prose: directories ending in ``/`` plus an optional ``.py`` leaf.
#: It must start a token, so ``hook_runtime/harness/`` never yields ``harness/`` (5.4.3).
_PATH: Final = re.compile(r"(?<![\w./-])(?:[A-Za-z_][\w-]*/)+(?:[A-Za-z_][\w-]*\.py)?(?![\w/-])")
_COLON_FORM: Final = re.compile(
    r"^(?:coding_agent_playbook|tests)(?:\.[A-Za-z_]\w*)+:[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*$"
)
_TOML_HEADER: Final = re.compile(r"^\s*\[\[?\s*([^\[\]]+?)\s*\]\]?\s*(?:#.*)?$")
_TOML_STRING: Final = re.compile(r'"([^"\\\n]*)"')
_YAML_COMMENT: Final = re.compile(r"(?:^|\s)(#.*)$")
_GENERATED_NOTE: Final = (
    "<!-- Generated by `python -m tests.architecture.module_moves apply` from the move map"
    " in tests/architecture/move_map/: edit the map, not this table. -->"
)


@dataclass(frozen=True, slots=True)
class Edit:
    """Replace ``text[start:end]`` with ``new``; a ``label`` replaces ``old -> new`` in check."""

    start: int
    end: int
    new: str
    label: str | None = None


class Line(NamedTuple):
    """One line of a text: 1-based number, offset of its first character, text, region."""

    number: int
    offset: int
    text: str
    region: str


class Resolver(Protocol):
    """Current spellings from the move map and one working tree (built by module_moves)."""

    def dotted(self, name: str) -> str | None:
        """The current spelling of a stale dotted name, or None when current or unmapped."""

    def path(self, path: str) -> str | None:
        """The current spelling of a stale repo-relative path, or None."""


def split_lines(text: str) -> list[Line]:
    """Every line of ``text`` (split on ``\\n`` only, so offsets match the text), region ``doc``.

    Example: ``split_lines("a\\nb")`` is ``[Line(1, 0, "a", "doc"), Line(2, 2, "b", "doc")]``.
    """
    lines, offset = [], 0
    for number, line in enumerate(text.split("\n"), start=1):
        lines.append(Line(number, offset, line, "doc"))
        offset += len(line) + 1
    return lines


def line_regions(text: str) -> list[Line]:
    """Every line tagged ``doc``, ``keep``, ``section`` (generated) or ``marker``.

    Raises ``ValueError`` naming the line of an unbalanced or nested marker.
    Example: ``[line.region for line in line_regions("a\\n<!-- module-moves: keep -->\\nb\\n<!-- module-moves: end-keep -->")]``
    is ``["doc", "marker", "keep", "marker"]``.
    """
    tagged: list[Line] = []
    inside: tuple[str, int] | None = None
    for line in split_lines(text):
        marker = line.text.strip()
        if marker in _MARKERS or marker in _CLOSERS:
            inside = _next_region(inside, marker, line.number)
            tagged.append(line._replace(region="marker"))
            continue
        tagged.append(line._replace(region=inside[0] if inside else "doc"))
    if inside is not None:
        raise ValueError(f"line {inside[1]}: a {inside[0]} marker is never closed")
    return tagged


def _next_region(
    inside: tuple[str, int] | None, marker: str, number: int
) -> tuple[str, int] | None:
    if marker in _MARKERS and inside is None:
        return _MARKERS[marker], number
    if marker in _CLOSERS and inside is not None and inside[0] == _CLOSERS[marker]:
        return None
    raise ValueError(
        f"line {number}: unexpected {marker!r}; expected {KEEP_START} ... {KEEP_END}"
        f" or {SECTION_START} ... {SECTION_END} pairs, never nested"
    )


def colon_or_dotted(name: str, resolver: Resolver) -> str | None:
    """The current spelling of ``a.b`` or ``a.b:attr`` (an entry-point value), or None.

    Example: ``colon_or_dotted("coding_agent_playbook._toml:dumps", resolver)`` is
    ``"coding_agent_playbook.toml_writer:dumps"`` once N1 has moved the module.
    """
    module, colon, attr = name.partition(":")
    if not colon:
        return resolver.dotted(name)
    current = resolver.dotted(f"{module}.{attr}")
    suffix = f".{attr}"
    if current is None or not current.endswith(suffix):
        return None
    return f"{current[: -len(suffix)]}:{attr}"


def doc_path(token: str, resolver: Resolver) -> str | None:
    """The current spelling of a path token, keeping its form (prefixed, ``tests/`` or bare).

    A bare one-segment directory (``harness/``) is never rewritten: in the SPEC §5.1
    tree it can be ``hook_runtime/harness/`` (5.4.3), so it is only reported.
    Example: ``doc_path("src/coding_agent_playbook/_toml.py", resolver)`` is
    ``"src/coding_agent_playbook/toml_writer.py"`` once N1 has moved the module.
    """
    if token.startswith("tests/"):
        return resolver.path(token)
    for prefix in (_ENGINE_DIR, "coding_agent_playbook/"):
        if token.startswith(prefix):
            return _engine_path(token.removeprefix(prefix), prefix, resolver)
    return _engine_path(token, "", resolver) if "/" in token.rstrip("/") else None


def _engine_path(relative: str, prefix: str, resolver: Resolver) -> str | None:
    current = resolver.path(_ENGINE_DIR + relative)
    if current is None or not current.startswith(_ENGINE_DIR):
        return None
    return prefix + current.removeprefix(_ENGINE_DIR)


def prose_edits(text: str, start: int, resolver: Resolver) -> list[Edit]:
    """R-DOC on one stretch of prose that starts at offset ``start`` of its file.

    Example: after N1, ``prose_edits("see `coding_agent_playbook._toml`", 0, resolver)``
    is ``[Edit(5, 32, "coding_agent_playbook.toml_writer")]``.
    """
    edits = [
        Edit(start + match.start(), start + match.end(), new)
        for match in _DOTTED.finditer(text)
        if (new := colon_or_dotted(match.group(), resolver)) is not None
    ]
    edits += [
        Edit(start + match.start(), start + match.end(), new)
        for match in _PATH.finditer(text)
        if (new := doc_path(match.group(), resolver)) is not None
    ]
    return edits


def markdown_edits(text: str, resolver: Resolver) -> list[Edit]:
    """R-DOC on a markdown file, skipping markers, kept history and the generated section.

    Example: ``markdown_edits(spec_text, resolver)`` leaves every line between
    ``<!-- module-moves: keep -->`` and ``<!-- module-moves: end-keep -->`` alone.
    """
    return [
        edit
        for line in line_regions(text)
        if line.region == "doc"
        for edit in prose_edits(line.text, line.offset, resolver)
    ]


def workflow_edits(text: str, resolver: Resolver) -> list[Edit]:
    """R-DOC on the comments of a workflow file (``.github/workflows/ci.yml``).

    Example: ``workflow_edits("run: x  # see tests/hooks/\\n", resolver)`` edits the
    comment only, never ``run:`` values.
    """
    edits: list[Edit] = []
    for line in split_lines(text):
        comment = _YAML_COMMENT.search(line.text)
        if comment is not None:
            edits += prose_edits(comment.group(1), line.offset + comment.start(1), resolver)
    return edits


def toml_edits(text: str, resolver: Resolver) -> list[Edit]:
    """R-TOML: entry-point values and the full dotted names of ``[tool.importlinter]``.

    Group headers (``[project.entry-points."coding_agent_playbook.adapters"]``) are
    never rewritten, and neither are container-relative names (``layers``).
    Example: under ``[project.entry-points."coding_agent_playbook.adapters"]``, the value
    ``"coding_agent_playbook.adapters.agent_harness_adapter:AgentHarnessAdapter"`` becomes
    ``"coding_agent_playbook.agent_harness.adapter:AgentHarnessAdapter"`` after AH-1.
    """
    edits: list[Edit] = []
    table = ""
    for line in split_lines(text):
        header = _TOML_HEADER.match(line.text)
        if header is not None:
            table = header.group(1)
            continue
        edits += _toml_line_edits(line, table, resolver)
    return edits


def _toml_line_edits(line: Line, table: str, resolver: Resolver) -> list[Edit]:
    strings = list(_TOML_STRING.finditer(line.text))
    if table == "project.scripts" or table.startswith("project.entry-points."):
        return [
            Edit(line.offset + match.start(1), line.offset + match.end(1), new)
            for match in strings
            if _COLON_FORM.match(match.group(1))
            and (new := colon_or_dotted(match.group(1), resolver)) is not None
        ]
    if table == "tool.importlinter" or table.startswith("tool.importlinter."):
        return [
            Edit(
                line.offset + match.start(1) + name.start(),
                line.offset + match.start(1) + name.end(),
                new,
            )
            for match in strings
            for name in _DOTTED.finditer(match.group(1))
            if (new := resolver.dotted(name.group())) is not None
        ]
    return []


def migration_table(rows: Sequence[tuple[str, str, str]]) -> str:
    """The generated lines between the MIGRATION.md section markers, one row per public move.

    Example: ``migration_table([("coding_agent_playbook._toml", "coding_agent_playbook.toml_writer", "N1")])``
    ends with ``"| `coding_agent_playbook._toml` | `coding_agent_playbook.toml_writer` | N1 |\\n"``.
    """
    if not rows:
        return f"{_GENERATED_NOTE}\nNo module has moved yet.\n"
    table = ["| Old module path | New module path | Moved by |", "| --- | --- | --- |"]
    table += [f"| `{old}` | `{new}` | {pr} |" for old, new, pr in rows]
    return "\n".join([_GENERATED_NOTE, *table]) + "\n"


def migration_edits(text: str, rows: Sequence[tuple[str, str, str]]) -> list[Edit]:
    """R-MIGRATION: regenerate the section between the markers; nothing when they are absent.

    Example: ``migration_edits(migration_text, rows)`` is ``[]`` once the section
    already equals ``migration_table(rows)``.
    """
    lines = line_regions(text)
    starts = [line for line in lines if line.text.strip() == SECTION_START]
    if not starts:
        return []
    end = next(line for line in lines if line.text.strip() == SECTION_END)
    begin = starts[0].offset + len(starts[0].text) + 1
    wanted = migration_table(rows)
    if text[begin : end.offset] == wanted:
        return []
    label = "the module paths section -> regenerated from the move map"
    return [Edit(begin, end.offset, wanted, label=label)]


def bare_name_reviews(lines: Iterable[Line], names: Collection[str]) -> list[str]:
    """``<line>: bare '<name>'`` for each bare root filename: reported, never rewritten (5.4.3).

    Example: ``bare_name_reviews(split_lines("see renderer.py"), {"renderer.py"})`` is
    ``["1: bare 'renderer.py'"]``.
    """
    if not names:
        return []
    pattern = re.compile(
        r"(?<![\w./-])(" + "|".join(re.escape(name) for name in sorted(names)) + r")(?![\w/-])"
    )
    return [
        f"{line.number}: bare '{match.group(1)}'"
        for line in lines
        for match in pattern.finditer(line.text)
    ]
