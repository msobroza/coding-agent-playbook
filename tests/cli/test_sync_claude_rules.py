"""``playbook sync`` and Claude Code's rule files (SPEC §10.3.1).

The ``claude_code`` adapter writes the rule sections to
``.claude/rules/coding-agent-playbook.md`` and leaves ``.claude/CLAUDE.md`` a
rule-free stub, because OpenCode v1 attaches ``.claude/CLAUDE.md`` when its read
tool opens a file under ``.claude/`` (once per uncompacted session, SPEC §10.6:
a second copy of the rules) and no OpenCode release checked (v1.19.3, v2 dev
24c7f7a) discovers ``.claude/rules/`` by default. These tests pin the end-to-end
layout: both files are written, locked and gitignored; a pre-upgrade
``.claude/CLAUDE.md`` (full rules) is rewritten to the stub; other
``.claude/rules/`` files stay the user's, and so does a same-named file without
the sentinel, a symlinked ``.claude/rules`` or a symlinked, hard-linked or
non-regular ``.claude/CLAUDE.md`` (refused, nothing written).
"""

from __future__ import annotations

import os
import sys
from typing import TYPE_CHECKING

import pytest

from coding_agent_playbook.config.files import FileSystemStateSource
from coding_agent_playbook.generated_output.sentinel import sentinel_line
from coding_agent_playbook.sync import pipeline as _sync
from tests.cli.hook_repo import tree
from tests.conftest import _DEFAULT_CONFIG
from tests.fakes import FakeGitClient

if TYPE_CHECKING:
    from collections.abc import Callable
    from pathlib import Path

_CLAUDE_MD = ".claude/CLAUDE.md"
_RULES_FILE = ".claude/rules/coding-agent-playbook.md"
_RULE_TEXT = "Use spaces, not tabs."
_GENERATED_LINE = "This file is generated by coding-agent-playbook."
_STUB = f"{sentinel_line('html')}\n# CLAUDE.md\n\n{_GENERATED_LINE}\n"
#: What ``.claude/CLAUDE.md`` held before the rules moved to the rules file.
_OLD_LAYOUT = (
    f"{sentinel_line('html')}\n# CLAUDE.md\n\n{_GENERATED_LINE}\n\n"
    f"## Style Guide\n\n{_RULE_TEXT}\n\n---\n"
)
_NO_CLAUDE_CONFIG = _DEFAULT_CONFIG.replace(
    'adapters_enabled = ["continue", "claude_code", "opencode"]',
    'adapters_enabled = ["continue", "opencode"]',
)
#: A user's own file that happens to take the engine's name (no sentinel line).
_USER_RULES = b"# My own team rules\nAlways use tabs.\n"

posix_only = pytest.mark.skipif(sys.platform == "win32", reason="POSIX symlinks")


@pytest.fixture
def repo(tmp_path: Path, make_synthetic_repo: Callable[..., Path]) -> Path:
    return make_synthetic_repo(tmp_path, rules=[("style-guide", f"{_RULE_TEXT}\n")])


def _read(repo: Path, rel: str) -> str:
    return (repo / rel).read_text(encoding="utf-8")


def _lock_paths(repo: Path) -> set[str]:
    lockfile = FileSystemStateSource(repo_root=repo).load_lockfile()
    assert lockfile is not None
    return {entry.path for entry in lockfile.entries}


def test_sync_writes_the_rules_file_and_a_rule_free_claude_md(repo: Path) -> None:
    assert _sync.execute(repo, git=FakeGitClient()) == 0

    assert _read(repo, _CLAUDE_MD) == _STUB
    assert _RULE_TEXT in _read(repo, _RULES_FILE)
    assert {_CLAUDE_MD, _RULES_FILE} <= _lock_paths(repo)
    gitignore = _read(repo, ".gitignore")
    assert f"\n/{_CLAUDE_MD}\n" in gitignore
    assert f"\n/{_RULES_FILE}\n" in gitignore


def test_resync_rewrites_an_old_layout_claude_md_to_the_stub(repo: Path) -> None:
    (repo / ".claude").mkdir()
    (repo / _CLAUDE_MD).write_text(_OLD_LAYOUT, encoding="utf-8")

    assert _sync.execute(repo, git=FakeGitClient()) == 0

    assert _read(repo, _CLAUDE_MD) == _STUB
    assert _RULE_TEXT in _read(repo, _RULES_FILE)
    assert _sync.execute(repo, check=True, git=FakeGitClient()) == 0


def test_check_reports_the_old_layout_as_drift(
    repo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert _sync.execute(repo, git=FakeGitClient()) == 0
    (repo / _CLAUDE_MD).write_text(_OLD_LAYOUT, encoding="utf-8")
    (repo / _RULES_FILE).unlink()
    capsys.readouterr()

    assert _sync.execute(repo, check=True, git=FakeGitClient()) == 1

    out = capsys.readouterr().out
    assert _CLAUDE_MD in out
    assert _RULES_FILE in out


def test_sync_never_touches_other_claude_rules_files(repo: Path) -> None:
    rules_dir = repo / ".claude" / "rules"
    rules_dir.mkdir(parents=True)
    team = rules_dir / "team.md"
    team.write_text("# Team rule\n", encoding="utf-8")
    tagged = rules_dir / "legacy.md"
    tagged.write_text(f"{sentinel_line('html')}\n# legacy\n", encoding="utf-8")

    assert _sync.execute(repo, git=FakeGitClient()) == 0
    assert _sync.execute(repo, git=FakeGitClient()) == 0

    assert team.read_text(encoding="utf-8") == "# Team rule\n"
    assert tagged.is_file()
    assert "team.md" not in _read(repo, ".gitignore")
    assert "legacy.md" not in _read(repo, ".gitignore")
    assert not {".claude/rules/team.md", ".claude/rules/legacy.md"} & _lock_paths(repo)


@pytest.mark.parametrize("tracked", [True, False], ids=["committed", "untracked"])
def test_sync_refuses_a_user_file_at_the_rules_path(
    repo: Path, capsys: pytest.CaptureFixture[str], tracked: bool
) -> None:
    """Regression: a same-named user file was overwritten (an untracked one lost
    for good). It is refused before any adapter writes, like the launcher."""
    user_file = repo / _RULES_FILE
    user_file.parent.mkdir(parents=True)
    user_file.write_bytes(_USER_RULES)
    git = FakeGitClient(tracked={_RULES_FILE} if tracked else set())
    before = tree(repo, skip=())

    assert _sync.execute(repo, git=git) == 1

    err = capsys.readouterr().err
    assert f"error: {_RULES_FILE}: it exists without the playbook sentinel" in err
    assert f"playbook sync stopped; {_RULES_FILE} was not changed" in err
    assert "Move or rename what is in the way" in err
    assert user_file.read_bytes() == _USER_RULES
    assert tree(repo, skip=()) == before  # no stub, no lockfile, no .gitignore edit


def test_check_reports_a_user_file_at_the_rules_path_as_unverifiable(
    repo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert _sync.execute(repo, git=FakeGitClient()) == 0
    (repo / _RULES_FILE).write_bytes(_USER_RULES)
    capsys.readouterr()

    assert _sync.execute(repo, check=True, git=FakeGitClient()) == 1

    out = capsys.readouterr().out
    assert f"Cannot verify {_RULES_FILE}: " in out
    assert "Generated content differs" not in out
    assert (repo / _RULES_FILE).read_bytes() == _USER_RULES


@posix_only
@pytest.mark.parametrize("linked", [".claude", ".claude/rules"])
def test_sync_refuses_a_symlinked_rules_directory(
    repo: Path,
    tmp_path_factory: pytest.TempPathFactory,
    capsys: pytest.CaptureFixture[str],
    linked: str,
) -> None:
    """Regression: a ``.claude/rules`` linked to a shared folder got the engine
    file written outside the repo, an absolute lockfile path and endless drift."""
    shared = tmp_path_factory.mktemp("shared")  # outside the repo (``repo`` is tmp_path)
    (repo / linked).parent.mkdir(parents=True, exist_ok=True)
    (repo / linked).symlink_to(shared, target_is_directory=True)
    before = tree(repo, skip=())

    assert _sync.execute(repo, git=FakeGitClient()) == 1
    assert _sync.execute(repo, check=True, git=FakeGitClient()) == 1

    captured = capsys.readouterr()
    assert f"{linked} is a symbolic link" in captured.err
    assert f"Cannot verify {_RULES_FILE}: {linked} is a symbolic link" in captured.out
    assert list(shared.rglob("*")) == []
    assert tree(repo, skip=()) == before


@posix_only
def test_sync_refuses_a_symlinked_claude_md(repo: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """Regression (review round 2): the common ``.claude/CLAUDE.md -> ../AGENTS.md``
    link was written through, so sync exited 0 with AGENTS.md cut to the 4-line
    stub (every AGENTS.md reader lost the rules) and ``--check`` reported drift
    no sync could clear. Refused like a linked rules file: nothing written."""
    assert _sync.execute(repo, git=FakeGitClient()) == 0
    (repo / _CLAUDE_MD).unlink()
    (repo / _CLAUDE_MD).symlink_to("../AGENTS.md")
    before = tree(repo, skip=())
    capsys.readouterr()

    assert _sync.execute(repo, git=FakeGitClient()) == 1
    assert _sync.execute(repo, check=True, git=FakeGitClient()) == 1

    captured = capsys.readouterr()
    assert f"error: {_CLAUDE_MD}: it is a symbolic link" in captured.err
    assert f"Cannot verify {_CLAUDE_MD}: it is a symbolic link" in captured.out
    assert _RULE_TEXT in _read(repo, "AGENTS.md")
    assert tree(repo, skip=()) == before


def test_sync_refuses_a_hard_linked_claude_md(
    repo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Regression (final review): a ``.claude/CLAUDE.md`` hard-linked to AGENTS.md
    (the usual stand-in for a file symlink on Windows) passed the symlink check,
    so sync exited 0 with AGENTS.md cut to the stub through the shared inode and
    ``--check`` reported drift no sync could clear. Refused, nothing written."""
    assert _sync.execute(repo, git=FakeGitClient()) == 0
    (repo / _CLAUDE_MD).unlink()
    os.link(repo / "AGENTS.md", repo / _CLAUDE_MD)
    before = tree(repo, skip=())
    capsys.readouterr()

    assert _sync.execute(repo, git=FakeGitClient()) == 1
    assert _sync.execute(repo, check=True, git=FakeGitClient()) == 1

    captured = capsys.readouterr()
    assert f"error: {_CLAUDE_MD}: it is a hard link" in captured.err
    assert f"Cannot verify {_CLAUDE_MD}: it is a hard link" in captured.out
    assert _RULE_TEXT in _read(repo, "AGENTS.md")
    assert tree(repo, skip=()) == before


def test_sync_refuses_a_hard_linked_rules_file(
    repo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """The engine-owned rules file hard-linked to another file (sentinel and all)
    would be truncated through the shared inode: refused like the stub."""
    assert _sync.execute(repo, git=FakeGitClient()) == 0
    other = repo / "keep" / "rules-copy.md"
    other.parent.mkdir()
    os.link(repo / _RULES_FILE, other)
    before = tree(repo, skip=())
    capsys.readouterr()

    assert _sync.execute(repo, git=FakeGitClient()) == 1
    assert _sync.execute(repo, check=True, git=FakeGitClient()) == 1

    captured = capsys.readouterr()
    assert f"error: {_RULES_FILE}: it is a hard link" in captured.err
    assert f"Cannot verify {_RULES_FILE}: it is a hard link" in captured.out
    assert tree(repo, skip=()) == before


def test_sync_refuses_a_directory_at_claude_md(
    repo: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Regression (final review): a directory at ``.claude/CLAUDE.md`` passed the
    pre-check, so sync wrote AGENTS.md and then died with an IsADirectoryError
    traceback. Refused before any adapter writes, with exit 1."""
    (repo / _CLAUDE_MD).mkdir(parents=True)
    before = tree(repo, skip=())

    assert _sync.execute(repo, git=FakeGitClient()) == 1

    assert f"error: {_CLAUDE_MD}: it is not a regular file" in capsys.readouterr().err
    assert tree(repo, skip=()) == before


def test_disabling_claude_code_settles_both_files(repo: Path) -> None:
    """Both paths are declared output locations, so the leftover policy may delete them."""
    assert _sync.execute(repo, git=FakeGitClient()) == 0
    (repo / ".coding-agent-playbook.toml").write_text(_NO_CLAUDE_CONFIG)

    assert _sync.execute(repo, git=FakeGitClient()) == 0

    assert not (repo / _CLAUDE_MD).exists()
    assert not (repo / _RULES_FILE).exists()
    assert not {_CLAUDE_MD, _RULES_FILE} & _lock_paths(repo)
