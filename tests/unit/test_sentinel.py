"""Tests for the import-light sentinel module (specs/prK-lifecycle-hooks.md §P3).

``_sentinel`` is the single home of the "this file is engine-generated" marker.
It must stay importable without Jinja or YAML (hook runtimes read it on the hot
path), and ``has_sentinel`` accepts exactly two anchored positions — line 1, or
the first body line after a leading YAML frontmatter block — never a substring
anywhere else in a file.
"""

from __future__ import annotations

import subprocess
import sys
from typing import TYPE_CHECKING

import pytest

from coding_agent_playbook import _sentinel, renderer
from coding_agent_playbook._sentinel import SENTINEL, has_sentinel, sentinel_line

if TYPE_CHECKING:
    from pathlib import Path

#: The text every shipped consumer's generated files already carry. Changing it
#: would make every consumer drift on upgrade, so it is pinned here verbatim.
_SHIPPED_SENTINEL = "AUTOGENERATED by coding-agent-playbook — edit in source, run 'playbook sync'"

_SUBPROCESS_TIMEOUT_S = 60


def _run_fresh_interpreter(code: str) -> str:
    """Run ``code`` in a fresh interpreter and return its stripped stdout."""
    completed = subprocess.run(
        [sys.executable, "-c", code],
        capture_output=True,
        text=True,
        check=True,
        timeout=_SUBPROCESS_TIMEOUT_S,
    )
    return completed.stdout.strip()


def test_renderer_reexports_sentinel() -> None:
    assert renderer.SENTINEL is _sentinel.SENTINEL


def test_sentinel_text_is_the_shipped_code_string() -> None:
    assert SENTINEL == _SHIPPED_SENTINEL


def test_sentinel_module_is_import_light() -> None:
    out = _run_fresh_interpreter(
        "import coding_agent_playbook._sentinel, sys; "
        "print('jinja2' in sys.modules, 'yaml' in sys.modules)"
    )
    assert out == "False False"


def test_sentinel_module_imports_nothing_at_runtime() -> None:
    # The package __init__ is loaded first so only _sentinel's own imports count.
    out = _run_fresh_interpreter(
        "import sys, coding_agent_playbook; before = set(sys.modules); "
        "import coding_agent_playbook._sentinel; "
        "print(sorted(set(sys.modules) - before))"
    )
    assert out == "['coding_agent_playbook._sentinel']"


@pytest.mark.parametrize(
    ("style", "expected"),
    [
        ("html", f"<!-- {_SHIPPED_SENTINEL} -->"),
        ("hash", f"# {_SHIPPED_SENTINEL}"),
        ("slash", f"// {_SHIPPED_SENTINEL}"),
    ],
)
def test_sentinel_line_styles(style: str, expected: str) -> None:
    assert sentinel_line(style) == expected  # type: ignore[arg-type]


def test_sentinel_line_rejects_unknown_style() -> None:
    with pytest.raises(ValueError, match=r"'xml'.*'hash'.*'html'.*'slash'"):
        sentinel_line("xml")  # type: ignore[arg-type]


_HTML = f"<!-- {_SHIPPED_SENTINEL} -->"
_FRONTMATTER = "---\nname: demo\ndescription: A demo\n---\n"


@pytest.mark.parametrize(
    "text",
    [
        pytest.param(f"{_HTML}\n# Title\n", id="line-1-html"),
        pytest.param(f"# {_SHIPPED_SENTINEL}\nset -eu\n", id="line-1-hash"),
        pytest.param(f"// {_SHIPPED_SENTINEL}\nexport default {{}};\n", id="line-1-slash"),
        pytest.param(f"{_HTML}\n---\nname: x\n---\nbody\n", id="line-1-before-frontmatter"),
        pytest.param(f"{_HTML}", id="line-1-no-newline"),
        pytest.param(f"{_FRONTMATTER}{_HTML}\n\nbody\n", id="first-body-line"),
        pytest.param(f"{_FRONTMATTER}{_HTML}", id="first-body-line-at-eof"),
        pytest.param(f"---\r\nname: demo\r\n---\r\n{_HTML}\r\nbody\r\n", id="first-body-line-crlf"),
        pytest.param(f"---\n---\n{_HTML}\nbody\n", id="empty-frontmatter"),
    ],
)
def test_has_sentinel_positions(text: str) -> None:
    assert has_sentinel(text) is True


@pytest.mark.parametrize(
    "text",
    [
        pytest.param("", id="empty"),
        pytest.param("# Hand-written notes\n", id="no-sentinel"),
        pytest.param(f"# Title\n{_HTML}\n", id="line-2-without-frontmatter"),
        pytest.param(f"intro\n\nsee below\n{_HTML}\n", id="deep-in-body"),
        pytest.param(f"{_FRONTMATTER}\n{_HTML}\n", id="second-body-line"),
        pytest.param(f"{_FRONTMATTER}# Title\n{_HTML}\n", id="later-body-line"),
        pytest.param(f"---\nnote: {_SHIPPED_SENTINEL}\n---\nbody\n", id="inside-frontmatter"),
        pytest.param(f"---\nname: demo\n{_HTML}\n", id="unterminated-frontmatter"),
        pytest.param("---\nname: demo\n---", id="frontmatter-without-body"),
        pytest.param(f"--- \nname: demo\n---\n{_HTML}\n", id="line-1-is-not-a-fence"),
        # The whole anchored line must be a sentinel line: prose quoting it is the user's.
        pytest.param(
            f"Files whose first line is `{_HTML}` are generated; never edit them.\n\nMy notes.\n",
            id="line-1-prose-quoting-it",
        ),
        pytest.param(f"{_FRONTMATTER}Note: {_HTML}\n", id="first-body-line-prose-quoting-it"),
        pytest.param(f"<!-- {_SHIPPED_SENTINEL} v0.4.0 -->\n", id="line-1-other-wording"),
        pytest.param(f"  {_HTML}\n", id="line-1-indented"),
    ],
)
def test_has_sentinel_rejects_unanchored_positions(text: str) -> None:
    assert has_sentinel(text) is False


# --- file_has_sentinel: the bounded head read shared by adapters and the hook runtime ----------

_WHOLE_TEXT_CASES = {
    "line-1": f"{_HTML}\n# Title\n",
    "line-1-crlf": f"{_HTML}\r\nbody\r\n",
    "first-body-line": f"{_FRONTMATTER}{_HTML}\n\nbody\n",
    "first-body-line-at-eof": f"{_FRONTMATTER}{_HTML}",
    "lone-cr-after-sentinel": f"{_HTML}\rjunk\nbody\n",
    "second-body-line": f"{_FRONTMATTER}\n{_HTML}\n",
    "unterminated-frontmatter": f"---\nname: demo\n{_HTML}\n",
    "fence-at-eof": "---\nname: x\n---",
    "prose-quoting-it": f"Lines like `{_HTML}` are generated.\n",
    "empty": "",
}


@pytest.mark.parametrize("text", list(_WHOLE_TEXT_CASES.values()), ids=list(_WHOLE_TEXT_CASES))
def test_file_has_sentinel_matches_has_sentinel_on_whole_text(tmp_path: Path, text: str) -> None:
    target = tmp_path / "f.md"
    target.write_bytes(text.encode("utf-8"))

    assert _sentinel.file_has_sentinel(target) is has_sentinel(text)
    assert _sentinel.file_has_sentinel(str(target)) is has_sentinel(text)


def test_file_has_sentinel_reads_bounded_head_and_is_binary_safe(tmp_path: Path) -> None:
    """Only line 1 (or a frontmatter block + one line) is read; bad bytes are user-owned."""
    big_body = "x" * (2 * _sentinel.SENTINEL_HEAD_BYTES) + "\n"
    plain = tmp_path / "plain.md"
    plain.write_text(f"# Title\n{big_body}", encoding="utf-8")
    fronted = tmp_path / "fronted.md"
    fronted.write_text(f"{_FRONTMATTER}{_HTML}\n{big_body}", encoding="utf-8")
    huge_frontmatter = tmp_path / "huge.md"
    huge_frontmatter.write_text(f"---\n{big_body}---\n{_HTML}\n", encoding="utf-8")
    binary = tmp_path / "blob.bin"
    binary.write_bytes(b"\xff\xfe\x00" + _HTML.encode() + b"\n")

    assert _sentinel._sentinel_head(plain) == b"# Title\n"
    assert _sentinel._sentinel_head(fronted) == f"{_FRONTMATTER}{_HTML}\n".encode()
    assert _sentinel.file_has_sentinel(fronted) is True
    assert _sentinel.file_has_sentinel(huge_frontmatter) is False
    assert _sentinel.file_has_sentinel(binary) is False
    assert _sentinel.file_has_sentinel(tmp_path / "missing.md") is False
    assert _sentinel.file_has_sentinel(tmp_path) is False  # a directory


def test_sentinel_text_is_injectable_for_a_rendered_guard_config() -> None:
    custom = "<!-- GENERATED -->\nbody\n"

    assert has_sentinel(custom, sentinel="GENERATED") is True
    assert has_sentinel(f"{_HTML}\n", sentinel="GENERATED") is False
    assert has_sentinel(f"{_HTML}\n", sentinel=SENTINEL) is True
