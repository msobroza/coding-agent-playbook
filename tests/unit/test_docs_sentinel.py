"""Docs-consistency guard: SPEC.md quotes the code sentinel verbatim (prK §P3).

``generated_output.sentinel.SENTINEL`` is canonical — changing it
would make every consumer's generated files drift on upgrade — so the SPEC must
quote it exactly, never the stale prose forms it carried before. Prose-only:
these tests read markdown, never engine behaviour.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from coding_agent_playbook.generated_output.sentinel import SENTINEL, sentinel_line

_SPEC = Path(__file__).resolve().parents[2] / "SPEC.md"

#: Wordings the SPEC used to show that no generated file ever carried.
_STALE_FORMS = (
    "AUTOGENERATED — edit in coding-agent-playbook",
    "AUTOGENERATED by coding-agent-playbook v0.4.0",
)


def _spec_text() -> str:
    return _SPEC.read_text(encoding="utf-8")


def _section(text: str, start_heading: str, end_heading: str) -> str:
    """Return the slice of ``text`` from ``start_heading`` up to ``end_heading``."""
    start = text.index(start_heading)
    return text[start : text.index(end_heading, start)]


def test_spec_quotes_code_sentinel() -> None:
    assert SENTINEL in _spec_text()


@pytest.mark.parametrize("stale", _STALE_FORMS)
def test_spec_carries_no_stale_sentinel_form(stale: str) -> None:
    assert stale not in _spec_text()


def test_spec_design_recap_quotes_code_sentinel() -> None:
    recap = _section(_spec_text(), "### 4.3 Key design choices", "## 5. Repository layout")
    assert SENTINEL in recap


def test_spec_example_headers_match_rendered_sentinel_line() -> None:
    headers = [line for line in _spec_text().splitlines() if line.startswith("<!-- AUTOGENERATED")]
    assert headers, "expected the SPEC's rendered-output examples to show the sentinel"
    assert set(headers) == {sentinel_line("html")}
