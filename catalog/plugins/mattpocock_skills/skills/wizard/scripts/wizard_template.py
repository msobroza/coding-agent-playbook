import contextlib
import getpass
import os
import re
import shlex
import sys
import tempfile
import urllib.parse
import webbrowser
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Callable, Mapping
    from typing import TextIO

# ──────────────────────────────────────────────────────────────────────────
# Wizard library: delightful, consistent UX, identical across every wizard.
# ──────────────────────────────────────────────────────────────────────────


def _use_color(stream: TextIO, environ: Mapping[str, str]) -> bool:
    """Colour only on a terminal that names a capable ``TERM`` (not unset, empty or dumb)."""
    return stream.isatty() and environ.get("TERM", "") not in ("", "dumb")


_COLOR = _use_color(sys.stdout, os.environ)


def _sgr(code: str) -> str:
    """The ANSI SGR escape for ``code`` when colour is on, else ``""``."""
    return f"\033[{code}m" if _COLOR else ""


BOLD = _sgr("1")
DIM = _sgr("2")
RESET = _sgr("0")
BLUE = _sgr("34")
GREEN = _sgr("32")
YELLOW = _sgr("33")
RED = _sgr("31")

# Author sets this at the top of the stages section.
TOTAL_STAGES = 0

_STAGE_INDEX = 0
ENV_FILE = os.environ.get("ENV_FILE") or ".env"
WRITTEN_ENV: list[str] = []  # KEYs written to ENV_FILE this run
WRITTEN_SECRET: list[str] = []  # secret NAMEs set this run
WRITTEN_VAR: list[str] = []  # variable NAMEs set this run
SKIPPED: list[str] = []  # things left for the human to do by hand

EXIT_NO_TERMINAL = 2
EXIT_INTERRUPTED = 130
_ENV_KEY_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_SCREEN_CLEAR = "\033[2J\033[3J\033[H"


def _out(text: str) -> None:
    """Write ``text`` to stdout and flush."""
    sys.stdout.write(text)
    sys.stdout.flush()


def _read_line() -> str:
    """One answer, trimmed of blanks; end of file reads as an empty answer."""
    try:
        return input().strip(" \t")
    except EOFError:
        return ""


def _clear() -> None:
    """_clear() wipes the terminal so only the current step is on screen. No-op when
    output isn't a terminal, so piped logs stay readable."""
    if sys.stdout.isatty() and os.environ.get("TERM") != "dumb":
        _out(_SCREEN_CLEAR)


def banner(title: str) -> None:
    """banner("Title") shows the opening frame: what this wizard does."""
    _clear()
    _out(f"\n{BOLD}{BLUE}  {title}{RESET}\n")
    _out(f"{DIM}  {TOTAL_STAGES} stages{RESET}\n\n")
    _out(f"{DIM}  You drive the browser; this wizard tells you exactly what to do and\n")
    _out("  captures the values you copy back. Stop any time with Ctrl-C and re-run\n")
    _out(f"  later, since it remembers values already saved.{RESET}\n")
    pause("Ready to start?")


def stage(name: str) -> None:
    """stage("Name") clears the screen, then announces a stage and shows progress.
    Clearing keeps only the current step on screen."""
    global _STAGE_INDEX
    _clear()
    _STAGE_INDEX += 1
    _out(f"\n{BOLD}{BLUE}▸ Stage {_STAGE_INDEX}/{TOTAL_STAGES} · {name}{RESET}\n")


def say(text: str) -> None:
    """say("...") prints a plain instruction line."""
    _out(f"  {text}\n")


def step(text: str) -> None:
    """step("...") is a numbered-feeling action the human takes in the browser."""
    _out(f"  {BLUE}•{RESET} {text}\n")


def note(text: str) -> None:
    """note("...") prints a dimmed line."""
    _out(f"  {DIM}{text}{RESET}\n")


def warn(text: str) -> None:
    """warn("...") prints a warning line."""
    _out(f"  {YELLOW}⚠ {text}{RESET}\n")


def _launchable(url: str) -> bool:
    """Whether ``url`` has a scheme and a host, so a browser can open it."""
    parts = urllib.parse.urlsplit(url)
    return bool(parts.scheme and parts.netloc)


def open_url(url: str) -> None:
    """open_url(url) opens it in the human's browser through Python's webbrowser
    module; an argument without a scheme and host is only printed."""
    if not _launchable(url):
        _out(f"  {GREEN}↗ go to{RESET} {url}\n")
        return
    _out(f"  {GREEN}↗ opening{RESET} {url}\n")
    try:
        opened = webbrowser.open(url, new=2)
    except (webbrowser.Error, OSError):
        warn(f"couldn't open a browser, so visit it manually: {url}")
        return
    if not opened:
        warn(f"couldn't open a browser; visit it manually: {url}")


def pause(message: str = "Press Enter to continue") -> None:
    """pause("msg") waits for the human to confirm they've done the manual part."""
    _out(f"  {DIM}{message}{RESET} ")
    _read_line()


def confirm(question: str) -> bool:
    """confirm("question") is a y/N gate; returns True on yes."""
    _out(f"  {YELLOW}? {question} [y/N] ")
    return _read_line().startswith(("y", "Y"))


def _check_env_key(key: str) -> None:
    """Refuse a key that cannot be a ``.env`` variable name."""
    if not _ENV_KEY_RE.fullmatch(key):
        raise ValueError(
            f".env key {key!r} must be an identifier such as STRIPE_SECRET_KEY "
            "(letters, digits and underscores, not starting with a digit)"
        )


def _env_lines(path: Path) -> list[bytes]:
    """The lines of ``path`` as bytes, kept byte for byte; ``[]`` when it is no file."""
    if not path.is_file():
        return []
    lines = path.read_bytes().split(b"\n")
    if lines[-1] == b"":
        lines.pop()
    return lines


def _existing(key: str) -> str:
    """_existing("KEY"): current value of KEY in ENV_FILE, if any."""
    prefix = key.encode() + b"="
    matches = [line for line in _env_lines(Path(ENV_FILE)) if line.startswith(prefix)]
    if not matches:
        return ""
    return matches[-1].split(b"=", 1)[1].decode("utf-8", "surrogateescape")


def _show_prompt(prompt: str, current: str) -> None:
    """Show ``prompt``, offering to keep the current value without printing it."""
    if current:
        _out(f"  {BOLD}{prompt}{RESET} {DIM}[Enter keeps current]{RESET} ")
    else:
        _out(f"  {BOLD}{prompt}{RESET} ")


def ask(key: str, prompt: str) -> str:
    """ask("KEY", "Prompt") returns the value read. Offers the existing .env value as
    a default on re-runs (Enter keeps it). Visible input (non-secret)."""
    _check_env_key(key)
    current = _existing(key)
    _show_prompt(prompt, current)
    answer = _read_line()
    return answer or current


def _read_secret() -> str:
    """One hidden answer, trimmed of blanks; end of file reads as an empty answer."""
    try:
        return getpass.getpass("").strip(" \t")
    except EOFError:
        return ""


def ask_secret(key: str, prompt: str) -> str:
    """ask_secret("KEY", "Prompt") is like ask, but input is hidden."""
    _check_env_key(key)
    current = _existing(key)
    _show_prompt(prompt, current)
    answer = _read_secret()
    return answer or current


def _replace_atomically(path: Path, data: bytes) -> None:
    """Write ``data`` to a temporary file next to ``path``, then move it into place."""
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(FileNotFoundError):
            Path(tmp).unlink()
        raise


def write_env(key: str, value: str) -> None:
    """write_env("KEY", value) upserts KEY=VALUE into ENV_FILE (creates it; replaces
    any existing line). Idempotent."""
    _check_env_key(key)
    path = Path(ENV_FILE)
    prefix = key.encode() + b"="
    kept = [line for line in _env_lines(path) if not line.startswith(prefix)]
    kept.append(prefix + value.encode("utf-8", "surrogateescape"))
    _replace_atomically(path, b"\n".join(kept) + b"\n")
    WRITTEN_ENV.append(key)
    _out(f"  {GREEN}✓ wrote{RESET} {key} → {ENV_FILE}\n")


def set_secret(name: str, value: str) -> None:
    """set_secret(name, value) walks the human through adding a GitHub Actions
    repository secret by hand: it shows the name, never the value, waits for their
    confirmation and records it for the summary; a "no" leaves it on the
    still-to-do list."""
    step("In the GitHub repo: Settings → Secrets and variables → Actions → New repository secret.")
    step(f"Name it {name} and paste the same value you just entered.")
    if confirm(f"Added the GitHub secret {name}?"):
        WRITTEN_SECRET.append(name)
        _out(f"  {GREEN}✓ set{RESET} GitHub secret {name}\n")
        return
    SKIPPED.append(f"GitHub secret {name} (set it by hand in the repo's CI settings)")
    warn(f"skipped GitHub secret {name}; set it later")


def set_var(name: str, value: str) -> None:
    """set_var(name, value) walks the human through adding a GitHub Actions repository
    variable (not secret) by hand: it shows the name and the value, waits for their
    confirmation and records it for the summary."""
    step(
        "In the GitHub repo: Settings → Secrets and variables → Actions → Variables → "
        "New repository variable."
    )
    step(f"Name it {name} and give it this value: {value}")
    if confirm(f"Added the GitHub variable {name}?"):
        WRITTEN_VAR.append(name)
        _out(f"  {GREEN}✓ set{RESET} GitHub variable {name}\n")
        return
    SKIPPED.append(f"GitHub variable {name}")
    warn(f"skipped GitHub variable {name}; set it later")


def finish() -> None:
    """finish() clears, then shows a closing summary of everything configured."""
    _clear()
    _out(f"\n{BOLD}{GREEN}  ✓ Setup complete{RESET}\n")
    if WRITTEN_ENV:
        note(f"wrote {len(WRITTEN_ENV)} value(s) to {ENV_FILE}: {' '.join(WRITTEN_ENV)}")
    if WRITTEN_SECRET:
        note(f"set {len(WRITTEN_SECRET)} GitHub secret(s): {' '.join(WRITTEN_SECRET)}")
    if WRITTEN_VAR:
        note(f"set {len(WRITTEN_VAR)} GitHub variable(s): {' '.join(WRITTEN_VAR)}")
    if SKIPPED:
        _out("\n")
        warn("still to do by hand:")
        for item in SKIPPED:
            note(f"  - {item}")
    _out("\n")


def _no_terminal_message(script: Path) -> str:
    """What to tell the agent when no human can answer at this terminal."""
    return (
        "This wizard needs a human at an interactive terminal, and stdin here is not one.\n"
        "Ask the user to run it in their own terminal:\n"
        f"    python3 {shlex.quote(str(script))}\n"
    )


def run_wizard(stages: Callable[[], None]) -> int:
    """Run ``stages`` with a human at the terminal; return the exit status.

    2 before anything is shown when stdin is not a terminal; 130 on Ctrl-C;
    otherwise 0. Example: ``raise SystemExit(run_wizard(wizard_stages))``.
    """
    if not sys.stdin.isatty():
        sys.stderr.write(_no_terminal_message(Path(__file__).resolve()))
        sys.stderr.flush()
        return EXIT_NO_TERMINAL
    try:
        stages()
    except KeyboardInterrupt:
        _out(f"{RESET}\n")
        warn("stopped. Re-run it later; it remembers values already saved.")
        return EXIT_INTERRUPTED
    return 0


