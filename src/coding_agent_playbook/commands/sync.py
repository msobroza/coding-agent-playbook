"""`playbook sync` — regenerate all artifacts (SPEC §12.2 / §12.3).

Two modes:
- write (default): reads the previous lockfile → runs detector → renders →
  adapters write → removes stale outputs (adapter ``cleanup_stale`` + the
  lockfile-driven sweep in :mod:`coding_agent_playbook.stale_outputs`) →
  stamps the lockfile (:mod:`coding_agent_playbook.output_ownership`).
- ``--check``: re-renders into a scratch copy and compares against the on-disk
  files; exits 1 if any differ, are missing, or are stale (generated by an
  earlier sync but no longer produced, and a sync would remove them).

Both exit 2 when the previous lockfile exists but cannot be read: it is the
record of what earlier syncs generated, so sync stops rather than lose it.
"""

