# How a lockfile load fails: a committed lockfile is a natural merge-conflict
# target (``tomllib.TOMLDecodeError`` is a ValueError), and
# ``Lockfile.from_dict`` raises KeyError/TypeError on a malformed shape.
_UNREADABLE_LOCKFILE_ERRORS: tuple[type[Exception], ...] = (
    OSError,
    ValueError,
    KeyError,
    TypeError,
)


class UnreadableLockfileError(Exception):
    """The previous lockfile exists but cannot be read; sync must not overwrite it."""


@dataclass(frozen=True)
class SyncOutcome:
    """What one render + dispatch + cleanup pass did.

    ``removed`` is the deduplicated union of adapter ``cleanup_stale`` and the
    lockfile-driven sweep. ``kept_modified`` lists stale outputs the sweep kept
    because they were edited after the sync that generated them, and
    ``kept_unverified`` unmodified ones it kept because only a pre-schema-2
    lockfile lists them.
    """

    written: tuple[Path, ...]
    removed: tuple[Path, ...]
    kept_modified: tuple[Path, ...]
    kept_unverified: tuple[Path, ...]


def _build_jinja_context(ctx: SyncContext) -> dict[str, object]:
    """Per SPEC §9.4: facts + project metadata + engine metadata.

    Helpers (``has_framework``, ``rule``) are registered on the env globals by
    :func:`build_environment`; the context dict carries only data fields.
    """
    context: dict[str, object] = dict(ctx.facts)
    context["project_name"] = ctx.config.project.name
    context["project_description"] = ctx.config.project.description
    context.update(dict(ctx.config.user_choices))
    context["engine_version"] = ctx.config.engine_version or _engine_version
    return context


def _render_rule_body(rule: Rule, context: dict[str, object], env: Environment) -> Rule:
    """Re-emit a Rule with ``body`` set to the Jinja-rendered output.

    Non-templated rules pass through verbatim. The template/body split lets
    callers re-render from ``template_body`` again (e.g. for inline
    inclusion from a prompt with a different context).
    """
    if rule.is_templated:
        rendered = render_string(rule.template_body, dict(context), env=env)
        return dataclasses.replace(rule, body=rendered)
    return rule


def _render_prompt_body(prompt: Prompt, context: dict[str, object], env: Environment) -> Prompt:
    """Render a prompt's body through Jinja, masking ``input_variables`` so
    the opencode placeholder substitution can still find them (SPEC §9.7 +
    the ``prompt_opencode_command`` contract in renderer.py)."""
    if not prompt.is_templated:
        return prompt
    safe_context = dict(context)
    # Per SPEC §9.7 / renderer's opencode contract: input_variables names
    # must not appear in the Jinja context, or {{ var }} placeholders get
    # expanded before the format-time substitution maps them to $ARGUMENTS.
    for var in prompt.frontmatter.input_variables or []:
        name = var.get("name") if isinstance(var, dict) else None
        if name and name in safe_context:
            del safe_context[name]
    rendered = render_string(prompt.template_body, safe_context, env=env)
    return dataclasses.replace(prompt, body=rendered)


def _build_lockfile(
    written_paths: Iterable[Path], repo_root: Path, engine_version: str
) -> Lockfile:
    """The new lockfile: the ownership record the next sync's sweep trusts.

    Entries come from :func:`owned_lock_entries` (logical repo-relative paths,
    never through a symlink), so it lists only files this sync generated.
    """
    # RFC 3339 Zulu timestamp for the lockfile per SPEC §14.4
    rendered_at = _dt.datetime.now(_dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    return Lockfile(
        schema_version=LOCKFILE_SCHEMA_VERSION,
        engine_version=engine_version,
        rendered_at=rendered_at,
        entries=owned_lock_entries(written_paths, repo_root),
    )


def _filter_applies_if[T: "Rule | Prompt"](
    artifacts: list[T],
    facts: Facts,
    repo_root: Path,
) -> list[T]:
    """Apply :func:`evaluate_predicate` to each artifact and drop the ones
    whose ``applies_if`` evaluates to False. Empty predicate → always pass.
    """
    kept: list[T] = []
    for artifact in artifacts:
        predicate = artifact.frontmatter.applies_if or {}
        if not predicate or evaluate_predicate(predicate, facts, repo_root=repo_root):
            kept.append(artifact)
    return kept


def _filter_skills(skills: list[Skill]) -> list[Skill]:
    """Skills are unconditional in v1 (no ``applies_if`` in the SKILL.md
    schema). Returned unchanged; kept as a hook for v2 to filter on a
    ``conditions:`` extension without churning the call site."""
    return list(skills)


def _resolve_repo_root(args: argparse.Namespace) -> Path:
    raw = getattr(args, "repo_root", None)
    if raw is None:
        return Path.cwd()
    return Path(raw)


def _load_previous_lockfile(ctx: SyncContext) -> Lockfile | None:
    """Read the lockfile the last sync wrote; ``None`` when there is none.

    Raises :class:`UnreadableLockfileError` when it exists but cannot be read.
    Regenerating it would drop every stale entry it records, so those outputs
    would never be removed; the user resolves it (either side of a merge
    conflict is a valid record) or deletes it to skip the sweep once.
    """
    try:
        return ctx.state_source.load_lockfile()
    except _UNREADABLE_LOCKFILE_ERRORS as exc:
        raise UnreadableLockfileError(
            f"cannot read the previous lockfile .coding-agent-playbook.lock ({exc}). It "
            "records which files earlier syncs generated, so sync stops rather than "
            "overwrite it. Resolve a merge conflict by taking either side (e.g. "
            "'git checkout --theirs .coding-agent-playbook.lock'), or delete the file "
            "to skip stale-output removal once, then re-run 'playbook sync'."
        ) from exc


def _run_sync(ctx: SyncContext) -> SyncOutcome:
    """Internal helper for write mode: dispatch, then remove stale outputs.

    The previous lockfile is read before any adapter writes: it is the record
    of what earlier syncs generated, which the stale-output sweep needs after
    the adapters and their ``cleanup_stale`` have run. Directories either pass
    empties are pruned.
    """
    previous_lockfile = _load_previous_lockfile(ctx)
    written, cleaned = _dispatch(ctx)
    prune_empty_parents(ctx.repo_root, cleaned)
    # Sentinel-less outputs (native skills' SKILL.md, scripts/, references/) and
    # the outputs of a now-disabled adapter are invisible to cleanup_stale; the
    # previous lockfile is their ownership record.
    sweep = sweep_stale_outputs(previous_lockfile, written, ctx.repo_root)
    return SyncOutcome(
        written=tuple(written),
        removed=tuple(dict.fromkeys([*cleaned, *sweep.removed])),
        kept_modified=sweep.kept_modified,
        kept_unverified=sweep.kept_unverified,
    )


def _dispatch(ctx: SyncContext) -> tuple[list[Path], list[Path]]:
    """Render, let every enabled adapter write and ``cleanup_stale``.

    Returns ``(written, cleaned)``. ``written`` keeps only the skill side files
    a skill's sources back (:func:`source_backed_skill_outputs`), so a file the
    adapter merely found in a copied ``scripts/`` / ``references/`` dir is
    neither protected from cleanup nor recorded as engine output.
    """
    rules = _filter_applies_if(ctx.rules_resolved, ctx.facts, ctx.repo_root)
    prompts = _filter_applies_if(ctx.prompts_resolved, ctx.facts, ctx.repo_root)
    skills = _filter_skills(ctx.skills_resolved)

    base_env = build_environment([], is_prompt_context=False)
    base_env.globals["_facts"] = dict(ctx.facts)
    base_context = _build_jinja_context(ctx)

    # Render rule bodies first (their template_body may also be re-rendered
    # by the registry when a prompt asks to inline them).
    rendered_rules = [_render_rule_body(rule, base_context, base_env) for rule in rules]

    registry = RuleRegistryImpl(rendered_rules, ctx.facts, base_env)
    prompt_env = build_environment([], is_prompt_context=True, rule_registry=registry)
    prompt_env.globals["_facts"] = dict(ctx.facts)
    rendered_prompts = [_render_prompt_body(p, base_context, prompt_env) for p in prompts]

    # Re-discover adapters with the rule_registry plumbed in so the
    # includes_rules appendix can resolve through the registry.
    adapters = discover_adapters(ctx.config, rule_registry=registry)
    ctx.adapters = adapters

    written: list[Path] = []
    for adapter in adapters.values():
        written.extend(
            _write_outputs(adapter, rendered_rules, rendered_prompts, skills, ctx.repo_root)
        )

    resolved_written: set[Path] = {p.resolve() for p in written}
    cleaned: list[Path] = []
    for adapter in adapters.values():
        cleaned.extend(adapter.cleanup_stale(resolved_written, ctx.repo_root))
    return written, cleaned


def _write_outputs(
    adapter: Adapter,
    rules: list[Rule],
    prompts: list[Prompt],
    skills: list[Skill],
    repo_root: Path,
) -> list[Path]:
    """Let one adapter write every artifact; return the paths the engine owns."""
    written: list[Path] = []
    for rule in rules:
        written.extend(adapter.write_rule(rule, repo_root))
    for prompt in prompts:
        written.extend(adapter.write_prompt(prompt, repo_root))
    for skill in skills:
        written.extend(source_backed_skill_outputs(skill, adapter.write_skill(skill, repo_root)))
    written.extend(adapter.finalize(repo_root))
    return written


def _warn_kept(outcome: SyncOutcome, repo_root: Path) -> None:
    """One stderr ``warning:`` line per stale output the sweep kept.

    The sweep returns ``repo_root / <lockfile path>``, so ``relative_to`` holds.
    """
    for path in outcome.kept_modified:
        print(
            f"warning: {path.relative_to(repo_root).as_posix()} was generated by an earlier "
            "sync and edited since, so it was kept; delete it by hand if no longer needed.",
            file=sys.stderr,
        )
    for path in outcome.kept_unverified:
        print(
            f"warning: {path.relative_to(repo_root).as_posix()} is listed by a lockfile from "
            "an older engine but was not generated by this sync; that lockfile format could "
            "also list files sync did not create, so it was kept; delete it by hand if no "
            "longer needed.",
            file=sys.stderr,
        )


def execute(repo_root: Path, *, check: bool = False) -> int:
    """Execute the sync pipeline.

    Programmatic entry point used by ``playbook init`` (to fire a sync after
    writing the config) and by tests that want to skip the argparse
    plumbing. The CLI's :func:`run` wrapper simply parses flags and
    forwards to here.
    """
    ctx = SyncContext.from_repo(repo_root)
    try:
        if check:
            return _run_check(ctx)
        outcome = _run_sync(ctx)
    except UnreadableLockfileError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    lockfile = _build_lockfile(outcome.written, ctx.repo_root, ctx.config.engine_version)
    ctx.state_source.save_lockfile(lockfile)

    _warn_kept(outcome, ctx.repo_root)
    print(f"Summary: {len(outcome.written)} files written, {len(outcome.removed)} removed")
    return 0


def run(args: argparse.Namespace) -> int:
    """Dispatch to write mode or ``--check`` mode."""
    return execute(repo_root=_resolve_repo_root(args), check=bool(getattr(args, "check", False)))


def _run_check(ctx: SyncContext) -> int:
    """``playbook sync --check``: render in a parallel scratch tree, compare bytes
    against the consumer repo. Exits 0 (no drift) or 1 (drift detected).

    Implementation choice: we dispatch against a temporary mirror of the
    consumer repo so adapters can write freely without mutating the real tree,
    then diff the rendered output against on-disk content. This avoids
    duplicating render logic. Drift is a written file that is missing or
    differs on disk, or a stale file a sync would remove: one the scratch
    run's adapter ``cleanup_stale`` removed, or one a dry-run sweep of the
    *real* tree would delete. The copy dereferences symlinks and splits hard
    links, so sweeping it could disagree with what a real sync does.
    """
    import shutil
    import tempfile

    previous_lockfile = _load_previous_lockfile(ctx)
    scratch_dir = Path(tempfile.mkdtemp(prefix="playbook-sync-check-"))
    try:
        scratch = scratch_dir / "repo"
        shutil.copytree(ctx.repo_root, scratch, symlinks=False, ignore_dangling_symlinks=True)
        written, cleaned = _dispatch(SyncContext.from_repo(scratch))
        real_written = [ctx.repo_root / _scratch_relative(path, scratch) for path in written]
        planned = sweep_stale_outputs(previous_lockfile, real_written, ctx.repo_root, dry_run=True)
        stale = {_scratch_relative(path, scratch) for path in cleaned}
        stale.update(path.relative_to(ctx.repo_root) for path in planned.removed)
        drift = [
            *_written_drift(written, scratch, ctx.repo_root),
            *_stale_drift(stale, ctx.repo_root),
        ]
        if drift:
            print("Drift detected:")
            for entry in drift:
                print(entry)
            return 1
        print("No drift detected.")
        return 0
    finally:
        shutil.rmtree(scratch_dir, ignore_errors=True)


def _scratch_relative(path: Path, scratch: Path) -> Path:
    """``path`` (inside the scratch copy, existing or not) relative to ``scratch``."""
    return path.resolve().relative_to(scratch.resolve())


def _written_drift(written: Iterable[Path], scratch: Path, repo_root: Path) -> list[str]:
    """Drift entries for scratch-written files missing or different on disk.

    State files (config, lockfile) are owned by the StateSource, never by an
    adapter, so they are excluded: the lockfile sync writes is not drift.
    """
    drift: list[str] = []
    for path in written:
        rel = _scratch_relative(path, scratch)
        if rel.name in STATE_FILE_NAMES:
            continue
        actual_path = repo_root / rel
        if not actual_path.is_file():
            drift.append(f"  {rel.as_posix()}\n    Missing on disk; run 'playbook sync' to create.")
        elif actual_path.read_bytes() != path.read_bytes():
            drift.append(
                f"  {rel.as_posix()}\n"
                "    Generated content differs from on-disk content.\n"
                "    Run 'playbook sync' to regenerate."
            )
    return drift


def _stale_drift(stale: Iterable[Path], repo_root: Path) -> list[str]:
    """Drift entries, sorted, for repo-relative stale files still in the repo."""
    return [
        f"  {rel.as_posix()}\n"
        "    Stale: generated by an earlier sync but no longer produced. "
        "Run 'playbook sync' to remove it."
        for rel in sorted(set(stale))
        if rel.name not in STATE_FILE_NAMES and os.path.lexists(repo_root / rel)
    ]
