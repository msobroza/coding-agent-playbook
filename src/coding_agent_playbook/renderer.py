"""Renderer subsystem: Jinja2 environment + format post-processing.

See SPEC.md §9. Frontmatter is parsed by the engine before this module runs
and is always treated as static YAML — only the body is rendered through Jinja.
File-extension dispatch: ``.md`` body is returned verbatim; ``.md.j2`` body is
rendered through Jinja2 with ``StrictUndefined`` so typos fail loudly.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING, Any, Protocol

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

if TYPE_CHECKING:
    from collections.abc import Sequence
    from pathlib import Path

# Aliases the CLI accepts as a short-form for --format. Resolved to the full
# internal name before render_for() dispatches.
FORMAT_ALIASES: dict[str, str] = {
    "continue": "continue_rule",
    "claude": "claude_md_section",
    "agents": "agents_md_section",
    "opencode": "prompt_opencode_command",
}

# All built-in formats. Adapters may register more via the renderer registry
# (future work — v1 just has the built-ins inline here).
BUILTIN_FORMATS: frozenset[str] = frozenset(
    {
        "continue_rule",
        "claude_md_section",
        "agents_md_section",
        "prompt_continue",
        "prompt_claude_command",
        "prompt_opencode_command",
    }
)

# Sentinel header text used by formats that ship an "AUTOGENERATED" banner.
SENTINEL = "AUTOGENERATED by coding-agent-playbook — edit in source, run 'playbook sync'"

# A leading ``--- ... ---`` frontmatter block; group 1 is the text after it.
_LEADING_FRONTMATTER_RE = re.compile(r"\A---\n.*?\n---\n(.*)\Z", re.DOTALL)

# A ``{{ rule("id") }}`` call in a prompt template; group 1 is the rule id.
# Whitespace- and trim-marker-tolerant (``{{rule("x")}}``, ``{{- rule('x') -}}``).
# The single definition both the appendix decision and ``playbook validate`` use.
RULE_CALL_RE = re.compile(r"\{\{-?\s*rule\s*\(\s*['\"]([^'\"]+)['\"]\s*\)\s*-?\}\}")


def with_sentinel_body(frontmatter: str, body: str) -> str:
    """Compose a generated file whose frontmatter must stay on line 1.

    Parsers such as OpenCode's (gray-matter) and the Agent Skills loaders only
    see frontmatter when the file *starts* with ``---``, so the :data:`SENTINEL`
    cannot be line 1 there: it is the **first body line** (an HTML comment),
    followed by a blank line and ``body``. ``frontmatter`` must start with ``---``.

    Example::

        with_sentinel_body("---\ndescription: d\n---", "Body\n")
    """
    return f"{frontmatter.rstrip('\n')}\n<!-- {SENTINEL} -->\n\n{body}"


def carries_engine_sentinel(text: str, *, after_frontmatter: bool = False) -> bool:
    """Whether ``text`` is engine output: the :data:`SENTINEL` on line 1, or —
    with ``after_frontmatter`` — the exact sentinel comment as the first line
    after a leading frontmatter block (the :func:`with_sentinel_body` layout).

    The second position is opt-in and must be the engine's own comment line, not
    a mention: a hand-written file with frontmatter whose prose quotes the
    sentinel is never mistaken for engine output. A UTF-8 BOM (added by some
    editors on save) is ignored.

    Example::

        carries_engine_sentinel(with_sentinel_body("---\na: b\n---", "x"), after_frontmatter=True)
    """
    text = text.removeprefix("\ufeff")
    if SENTINEL in text.split("\n", 1)[0]:
        return True
    if not after_frontmatter:
        return False
    match = _LEADING_FRONTMATTER_RE.match(text)
    return match is not None and match.group(1).split("\n", 1)[0].strip() == f"<!-- {SENTINEL} -->"


