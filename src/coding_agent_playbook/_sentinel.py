"""The engine-generated-file sentinel — one string, importable without Jinja.

Every file ``playbook sync`` renders carries :data:`SENTINEL` so cleanup (and,
later, hook guards) can tell engine output from user-authored files. This module
is the single home of that marker and performs **zero runtime imports**: hook
runtimes read it on the hot path, where ``renderer`` (which pulls in ``jinja2``
and ``yaml`` at import time) is off-limits. ``renderer.SENTINEL`` re-exports it.

The text is canonical as shipped: changing it would make every consumer's
generated files drift on upgrade (specs/prK-lifecycle-hooks.md §P3).
"""

# A local constant instead of ``typing.TYPE_CHECKING`` keeps the module free of
# runtime imports; mypy treats any name ``TYPE_CHECKING`` as true.
TYPE_CHECKING = False
if TYPE_CHECKING:
    from typing import Literal

    SentinelStyle = Literal["html", "hash", "slash"]

SENTINEL = "AUTOGENERATED by coding-agent-playbook — edit in source, run 'playbook sync'"

#: Comment delimiters per style: markdown (``html``), engine-generated
#: shell/YAML/TOML files (``hash``), and the JS plugin shim (``slash``).
_STYLE_DELIMITERS: dict[str, tuple[str, str]] = {
    "html": ("<!-- ", " -->"),
    "hash": ("# ", ""),
    "slash": ("// ", ""),
}

_FRONTMATTER_FENCE = "---"


def sentinel_line(style: "SentinelStyle") -> str:
    """Return the sentinel wrapped in ``style``'s comment syntax, without a newline.

    Example::

        >>> sentinel_line("html")
        "<!-- AUTOGENERATED by coding-agent-playbook — edit in source, run 'playbook sync' -->"
    """
    delimiters = _STYLE_DELIMITERS.get(style)
    if delimiters is None:
        raise ValueError(
            f"unknown sentinel style {style!r}; expected one of {sorted(_STYLE_DELIMITERS)}"
        )
    opener, closer = delimiters
    return f"{opener}{SENTINEL}{closer}"


def has_sentinel(text: str) -> bool:
    """Whether ``text`` carries :data:`SENTINEL` at one of its two anchored positions.

    The positions are line 1, or — for files that must open with a YAML
    frontmatter fence (agent_harness output, SPEC §10.7.3) — the first body line
    right after the closing ``---``. A sentinel anywhere else is ordinary prose
    (``SPEC.md`` and test fixtures quote it), so it never marks a file as
    engine-generated.

    Example::

        >>> has_sentinel(sentinel_line("html") + "\\n# Title\\n")
        True
        >>> has_sentinel("---\\nname: x\\n---\\n" + sentinel_line("html") + "\\n")
        True
        >>> has_sentinel("# Notes\\n" + sentinel_line("html") + "\\n")
        False
    """
    lines = text.split("\n")
    if SENTINEL in lines[0]:
        return True
    body_line = _first_body_line(lines)
    return body_line is not None and SENTINEL in body_line


def _first_body_line(lines: list[str]) -> str | None:
    """Return the line right after a leading frontmatter block, else ``None``.

    Fence detection mirrors ``types.split_frontmatter``: a line equal to ``---``
    once its ``\\r`` is stripped. No leading fence, no closing fence, or nothing
    after the closing fence all mean there is no first body line.
    """
    if lines[0].rstrip("\r") != _FRONTMATTER_FENCE:
        return None
    for index in range(1, len(lines) - 1):
        if lines[index].rstrip("\r") == _FRONTMATTER_FENCE:
            return lines[index + 1]
    return None
