"""AGENTS.md adapter. See SPEC.md §10.4.

Composes a single ``AGENTS.md`` file at the repo root from buffered rule
sections. Prompts and skills are no-ops: AGENTS.md is rules-only.

This adapter always runs regardless of which other adapters are enabled (the
orchestrator enforces that invariant — the adapter itself just buffers rules
and finalizes the file).
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, ClassVar

from coding_agent_playbook._sentinel import sentinel_line
from coding_agent_playbook.adapters.base import Adapter
from coding_agent_playbook.renderer import render_for

if TYPE_CHECKING:
    from coding_agent_playbook._typing import Prompt, Rule, Skill

_AGENTS_MD_TITLE = "# AGENTS.md\n\nThis file is generated by coding-agent-playbook.\n"


class AgentsMdAdapter(Adapter):
    """Translate canonical rules into a single ``AGENTS.md`` at repo root.

    Rules-only by design: prompts and skills route through other adapters
    (Continue / Claude Code / OpenCode / shared_skills) — AGENTS.md is the
    universal "rules" surface every coding assistant agrees to read.
    """

    name = "agents_md"

    output_locations: ClassVar[tuple[str, ...]] = ("AGENTS.md",)

    def __init__(self) -> None:
        # (priority, rule_id, rendered_section). Buffered now, sorted and
        # written at finalize() time so the on-disk order is stable across
        # syncs regardless of the orchestrator's iteration order.
        self._buffered_rules: list[tuple[int, str, str]] = []

    def write_rule(self, rule: Rule, repo_root: Path) -> list[Path]:
        """Render a rule to the shared markdown-section format and buffer it.

        Returns ``[]``: nothing is written until ``finalize`` composes the
        single ``AGENTS.md`` file.
        """
        rendered = render_for(
            rule.source_path or Path("inline"),
            rule.body,
            "agents_md_section",
            frontmatter=rule.frontmatter.__dict__,
        )
        self._buffered_rules.append((rule.frontmatter.priority, rule.frontmatter.id, rendered))
        return []

    def write_prompt(self, prompt: Prompt, repo_root: Path) -> list[Path]:
        """No-op: AGENTS.md is rules-only.

        Prompts are emitted by harness-specific adapters (Continue, Claude
        Code, OpenCode). The orchestrator passes every prompt to every
        adapter; this one declines.
        """
        return []

    def write_skill(self, skill: Skill, repo_root: Path) -> list[Path]:
        """No-op: AGENTS.md is rules-only.

        Native skill emission belongs to the skill adapters (``claude_code``,
        ``opencode``, ``shared_skills``), which share one ``SkillWriter``. This
        adapter never degrades a skill to a prompt either (the default Adapter
        degrade path), since prompts are also no-ops here.
        """
        return []

    def finalize(self, repo_root: Path) -> list[Path]:
        """Compose ``AGENTS.md`` at ``repo_root`` from the buffered rules.

        Rules are sorted by ``(priority, id)`` so the on-disk layout is
        stable across syncs. The file is *always* overwritten if there is at
        least one rule; if the buffer is empty, nothing is written (and any
        stale file is cleaned up by :meth:`cleanup_stale`).
        """
        if not self._buffered_rules:
            return []
        sorted_rules = sorted(self._buffered_rules, key=lambda entry: (entry[0], entry[1]))
        sections = [rendered for _, _, rendered in sorted_rules]
        # Each section already ends with the section separator + trailing
        # newline. Joining with "\n" stacks them without introducing blank
        # gaps; the sentinel + title preamble seeds the file.
        content = f"{sentinel_line('html')}\n{_AGENTS_MD_TITLE}\n" + "\n".join(sections)
        agents_md = repo_root / "AGENTS.md"
        agents_md.parent.mkdir(parents=True, exist_ok=True)
        agents_md.write_text(content, encoding="utf-8")
        return [agents_md]

    def stale_outputs(self, written_paths: set[Path], repo_root: Path) -> list[Path]:
        """Report ``AGENTS.md`` as stale only if (a) it exists, (b) the engine
        wrote it (sentinel-tagged per :meth:`Adapter._carries_sentinel`), and (c)
        it was *not* re-written this sync (absent from ``written_paths``).

        AGENTS.md is a single repo-root file rather than a directory of
        sentinel-tagged artifacts, so the shared directory scan on the ABC does
        not apply. The ABC's ``cleanup_stale`` deletes what this returns, which
        keeps cleanup conservative: user-authored files and just-rendered files
        are both safe.
        """
        agents_md = repo_root / "AGENTS.md"
        if not agents_md.is_file() or agents_md.resolve() in written_paths:
            return []
        return [agents_md] if self._carries_sentinel(agents_md) else []
