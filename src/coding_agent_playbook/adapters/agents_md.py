"""AGENTS.md adapter. See SPEC.md §10.4.

Composes a single ``AGENTS.md`` file at the repo root: the always rules' sections,
then a generated ``## Where guidance lives`` section mapping file kinds to the
skills that hold the detailed conventions (kept only while an enabled adapter
writes a native skills root), then a trailing ``## Guardrails`` section with one
line per enabled hook that has guardrail text (D6, specs/prS-skills-context.md
8.4.2); the full text is in the ``playbook-guardrails`` skill. A member rule
(one that names a skill in ``skill:``) is dropped here:
it reaches its readers as a reference of that skill, written by the skill
adapters (ADR 0001, specs/prS-skills-context.md 6.4.6). Prompts are no-ops, and
a skill only contributes its Where line.

This adapter always runs regardless of which other adapters are enabled (the
orchestrator enforces that invariant — the adapter itself just buffers rules
and finalizes the file).
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, ClassVar

from coding_agent_playbook.adapters._where_guidance import WhereGuidanceBuffer
from coding_agent_playbook.adapters.base import Adapter
from coding_agent_playbook.generated_output.output_io import write_output_text
from coding_agent_playbook.generated_output.sentinel import sentinel_line
from coding_agent_playbook.hooks.enforcement import guardrail_line, guardrails_section
from coding_agent_playbook.renderer import render_for
from coding_agent_playbook.skills.membership import is_skill_member

if TYPE_CHECKING:
    from coding_agent_playbook.artifacts.prompt import Prompt
    from coding_agent_playbook.artifacts.rule import Rule
    from coding_agent_playbook.artifacts.skill import Skill
    from coding_agent_playbook.hooks.resolution.resolved import ResolvedHook

_AGENTS_MD_TITLE = "# AGENTS.md\n\nThis file is generated by coding-agent-playbook.\n"


class AgentsMdAdapter(Adapter):
    """Translate canonical always rules into a single ``AGENTS.md`` at repo root.

    Always rules only, by design: prompts, skills and the member rules they
    deliver route through other adapters (Continue / Claude Code / OpenCode /
    shared_skills) — AGENTS.md is the universal always-loaded surface every
    coding assistant agrees to read, so it points at those skills instead.
    """

    name = "agents_md"

    output_locations: ClassVar[tuple[str, ...]] = ("AGENTS.md",)

    # AGENTS.md is the always-rules surface (ADR 0001): a member rule reaches its
    # readers as a reference of the skill it names, which a skill adapter writes,
    # so this adapter alone never counts as delivering member rules.
    delivers_member_rules: ClassVar[bool] = False

    def __init__(self) -> None:
        # (priority, rule_id, rendered_section). Buffered now, sorted and
        # written at finalize() time so the on-disk order is stable across
        # syncs regardless of the orchestrator's iteration order.
        self._buffered_rules: list[tuple[int, str, str]] = []
        # (hook_id, guardrail line). One contiguous section sorted by id (L1),
        # not interleaved with the rules by priority as write_rule would.
        self._buffered_hooks: list[tuple[str, str]] = []
        self._where = WhereGuidanceBuffer()
        # The map names skills, so it needs an enabled adapter that writes them
        # (C7). True until the dispatch says otherwise: a caller driving this
        # adapter by hand keeps the map, as before note_native_skill_roots existed.
        self._skills_are_written = True

    def note_native_skill_roots(self, roots: frozenset[str]) -> None:
        """Keep the ``## Where guidance lives`` map only when some enabled adapter writes skills.

        With ``adapters_enabled = []`` or only ``continue``, no skill root is
        written, so a Where line would name a skill no AGENTS.md reader can load
        (specs/prS-skills-context.md C7). Called by the dispatch before
        :meth:`begin_sync`.

        Example: ``adapter.note_native_skill_roots(frozenset())`` -> no Where section.
        """
        self._skills_are_written = bool(roots)

    def write_rule(self, rule: Rule, repo_root: Path) -> list[Path]:
        """Render a rule that names no skill to the shared markdown-section format; buffer it.

        A member rule is skipped (E3): dispatch hands every rule to every
        adapter, and its skill's reference delivers it, not this file. Returns ``[]``:
        nothing is written until ``finalize`` composes the single ``AGENTS.md``.

        Example: ``adapter.write_rule(member_rule, repo_root)`` -> ``[]``, nothing buffered.
        """
        if is_skill_member(rule):
            return []
        rendered = render_for(
            rule.source_path or Path("inline"),
            rule.body,
            "agents_md_section",
            frontmatter=rule.frontmatter.__dict__,
        )
        self._buffered_rules.append((rule.frontmatter.priority, rule.frontmatter.id, rendered))
        return []

    def write_hook(self, hook: ResolvedHook, repo_root: Path) -> list[Path]:
        """Buffer the hook's one guardrail line for the Guardrails section (D6).

        Every enabled hook lands here, enforced elsewhere or not: Codex, Cursor
        and the other AGENTS.md readers see this line, and the skill named in
        the section's preface has the full text. A hook with no advisory (blank
        body, ``[hooks] advisory = false``) adds nothing. Returns ``[]``:
        ``finalize`` writes the file.

        Example: ``adapter.write_hook(hook, repo_root)`` buffers ``- `<id>`: <summary>``.
        """
        if hook.advisory is not None:
            self._buffered_hooks.append((hook.id, guardrail_line(hook.id, hook.guardrail_text)))
        return []

    def write_prompt(self, prompt: Prompt, repo_root: Path) -> list[Path]:
        """No-op: AGENTS.md is rules-only.

        Prompts are emitted by harness-specific adapters (Continue, Claude
        Code, OpenCode). The orchestrator passes every prompt to every
        adapter; this one declines.
        """
        return []

    def write_skill(self, skill: Skill, repo_root: Path) -> list[Path]:
        """Buffer ``skill``'s ``## Where guidance lives`` line; write nothing.

        Native skill emission belongs to the skill adapters (``claude_code``,
        ``opencode``, ``shared_skills``), which share one ``SkillWriter``. This
        adapter never degrades a skill to a prompt either (the default Adapter
        degrade path). Only a skill with member rules and a ``playbook.files``
        phrase adds a line, and only when an enabled adapter writes skills
        (:meth:`note_native_skill_roots`).
        Example: ``adapter.write_skill(python_coding, root)`` -> ``[]``.
        """
        if self._skills_are_written:
            self._where.add(skill)
        return []

    def finalize(self, repo_root: Path) -> list[Path]:
        """Compose ``AGENTS.md`` at ``repo_root`` from the buffered rules, skills and hooks.

        Title, always rules sorted by ``(priority, id)``, the Where section,
        then the Guardrails lines sorted by hook id, so the on-disk layout is
        stable across syncs. The file is *always* overwritten if there is at
        least one always rule, Where entry or hook advisory (a hooks-only repo still
        gets one, SPEC §4.3); with none, nothing is written (and any stale file
        is cleaned up by :meth:`cleanup_stale`). Without member skills or hook
        advisories the bytes are exactly the rules-only file.

        Example: ``adapter.finalize(repo_root)`` -> ``[repo_root / "AGENTS.md"]``.
        """
        sorted_rules = sorted(self._buffered_rules, key=lambda entry: (entry[0], entry[1]))
        sections = self._where.after([rendered for _, _, rendered in sorted_rules])
        if not (sections or self._buffered_hooks):
            return []
        # Each section already ends with the section separator + trailing
        # newline. Joining with "\n" stacks them without introducing blank
        # gaps; the sentinel + title preamble seeds the file.
        content = f"{sentinel_line('html')}\n{_AGENTS_MD_TITLE}\n" + "\n".join(sections)
        if self._buffered_hooks:
            content += ("\n" if sections else "") + guardrails_section(self._buffered_hooks)
        agents_md = repo_root / "AGENTS.md"
        agents_md.parent.mkdir(parents=True, exist_ok=True)
        write_output_text(agents_md, content)
        return [agents_md]

    def stale_outputs(self, written_paths: set[Path], repo_root: Path) -> list[Path]:
        """Report ``AGENTS.md`` as stale only if (a) it exists, (b) the engine
        wrote it (sentinel-tagged per :meth:`Adapter._carries_sentinel`), and (c)
        it was *not* re-written this sync (absent from ``written_paths``).

        AGENTS.md is a single repo-root file rather than a directory of
        sentinel-tagged artifacts, so the shared directory scan on the ABC does
        not apply. The ABC's ``cleanup_stale`` deletes what this returns, which
        keeps cleanup conservative: user-authored files and just-rendered files
        are both safe.
        """
        agents_md = repo_root / "AGENTS.md"
        if not agents_md.is_file() or agents_md.resolve() in written_paths:
            return []
        return [agents_md] if self._carries_sentinel(agents_md) else []
